<?php

use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

/*
|--------------------------------------------------------------------------
| Базовый класс тестов
|--------------------------------------------------------------------------
|
| Feature-тесты работают с приложением целиком и с реальной базой, поэтому
| получают RefreshDatabase: каждый тест идёт в транзакции, которая
| откатывается после прогона. Без этого повторный запуск падал бы на
| данных, оставшихся от предыдущего.
|
| Unit-тесты приложение не поднимают — им TestCase не нужен.
|
*/

pest()->extend(TestCase::class)
    ->use(RefreshDatabase::class)
    ->in('Feature');
