<?php

use App\Models\Setting;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Pagination\Paginator;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\DB;
use Tests\TestCase;

/*
|--------------------------------------------------------------------------
| Базовый класс тестов
|--------------------------------------------------------------------------
|
| Feature-тесты работают с приложением целиком и с реальной базой, поэтому
| получают RefreshDatabase: каждый тест идёт в транзакции, которая
| откатывается после прогона. Без этого повторный запуск падал бы на
| данных, оставшихся от предыдущего.
|
| Unit-тесты приложение не поднимают — им TestCase не нужен.
|
*/

pest()->extend(TestCase::class)
    ->use(RefreshDatabase::class)
    ->in('Feature');

/*
 * Умолчательные виды пагинации, снятые до первого теста.
 *
 * Снимок делается здесь, на загрузке файла: Livewire подменяет эти статики
 * при первом же своём компоненте, и снятое позже значение было бы уже
 * подменённым.
 */
$paginationDefaults = [Paginator::$defaultView, Paginator::$defaultSimpleView];

/*
 * Состояние, переживающее откат транзакции. RefreshDatabase возвращает базу,
 * но не трогает ни Redis, ни статики классов.
 *
 * 1. Кеш настроек живёт в Redis: без сброса настройки, записанные одним
 *    тестом, протекают в следующий и делают падения неповторяемыми.
 *
 * 2. Вид пагинации — статик `Paginator::$defaultView`. Любой Livewire-компонент
 *    с `WithPagination` подменяет его на `livewire::tailwind`
 *    (`SupportPagination::overrideDefaultPaginationViews()`), а восстанавливает
 *    только при штатном уничтожении компонента — которого при обычном
 *    HTTP-запросе к странице Filament не происходит. После такого теста
 *    публичные страницы рендерят пагинацию кнопками `wire:click` вместо
 *    ссылок, и падает не тот тест, который это устроил, а первый же
 *    следующий, проверяющий ссылки пагинации. В обычном порядке прогона
 *    такой пары не складывается, в обратном — складывается.
 */
pest()->beforeEach(function () use ($paginationDefaults): void {
    Setting::flushCache();

    Paginator::defaultView($paginationDefaults[0]);
    Paginator::defaultSimpleView($paginationDefaults[1]);
})->in('Feature');

/*
|--------------------------------------------------------------------------
| Общие помощники
|--------------------------------------------------------------------------
*/

/**
 * Сбросить счётчики лимитеров публичных форм.
 *
 * Счётчик живёт в Redis, а RefreshDatabase откатывает только базу — та же
 * причина, что и у сброса кеша настроек выше. Без сброса тест, упёршийся
 * в лимит заявок, оставляет счётчик следующим, и падать начинает не он,
 * а произвольный соседний тест, отправляющий форму: связь между причиной
 * и симптомом при этом не читается.
 *
 * Вызывать в `beforeEach` каждого файла, который отправляет форму заявки,
 * — глобально не ставится, потому что остальным тестам проекта лишний
 * flush не нужен. Redis кеша в тестах отдельный (REDIS_CACHE_DB=2
 * в `phpunit.xml`): очередь и сессии живут в другой базе и не задеваются.
 */
function resetRateLimiters(): void
{
    Cache::flush();
}

/**
 * Сколько запросов к базе делает вызов.
 *
 * Абсолютное число здесь важно меньше, чем его неизменность при росте
 * выдачи: именно так N+1 отличается от «просто нескольких запросов».
 * Проверяя счётчик, обязательно задавать и нижнюю границу — правило
 * RULES.md: выборка, не поймавшая ни одного запроса, иначе проходит
 * вхолостую.
 */
function countQueries(callable $callback): int
{
    $queries = 0;

    DB::listen(static function () use (&$queries): void {
        $queries++;
    });

    $callback();

    return $queries;
}
