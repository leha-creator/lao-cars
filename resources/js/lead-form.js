/**
 * Отправка формы заявки без перезагрузки страницы (веха 4.7).
 *
 * Компонент кладётся ПОВЕРХ обычной POST-формы и ничего в ней не заменяет:
 * `action`, `method`, `@csrf` и кнопка `type="submit"` остаются в разметке,
 * а обработчик висит на `submit.prevent`. При неработающем `app.js` форма
 * отправляется браузером и получает прежний редирект с баннером успеха.
 *
 * Это не осторожность, а сквозное правило проекта: фильтры каталога
 * работают без скрипта, фотогалерея деградирует до стопки изображений,
 * клик по строке прайса без скрипта доводит до формы. Форма заявки —
 * единственное, ради чего сайт существует, и ломать её молча нельзя тем
 * более. Вариант «кнопка `type="button"` с обработчиком» отклонён именно
 * поэтому: он выглядит короче и ломает форму полностью и без единой ошибки.
 *
 * Регистрация живёт ЗДЕСЬ, в модуле, который импортирует `app.js` до
 * `Alpine.start()`, а не в `@push('scripts')`. Правило `RULES.md` запрещает
 * второе, и его обоснование (пушнутый скрипт исполняется либо раньше
 * модуля из `<head>`, либо уже после старта Alpine) к регистрации внутри
 * самого модуля не относится: `Alpine.data()` перед `Alpine.start()`
 * отрабатывает всегда. Правило при этом не смягчается — инлайновый
 * `x-data` остаётся нормой для коротких компонентов, а сюда код уехал
 * по объёму: `fetch`, разбор четырёх кодов ответа и состояние ошибок
 * по полям в атрибут не помещаются и не отлаживаются.
 */

/** Сообщение, когда ответ невозможно разобрать или сеть недоступна. */
const FALLBACK_MESSAGE =
    'Не удалось отправить заявку. Проверьте соединение и попробуйте ещё раз или позвоните нам.';

/** Сообщение на протухшую сессию (419). */
const EXPIRED_MESSAGE = 'Страница устарела — обновите её и отправьте форму заново.';

export default function leadForm() {
    return {
        /** Идёт ли запрос. Блокирует кнопку: двойной клик даёт две заявки. */
        sending: false,

        /**
         * Ошибки по именам полей: `{ phone: 'Укажите телефон', … }`.
         *
         * Клиентские контейнеры ошибок стоят РЯДОМ с блейдовскими `@error`,
         * а не вместо них, и это безопасно: `@error` печатается только после
         * редиректа, то есть только на пути без JavaScript, а эти — только
         * при живом `fetch`. Одновременно они появиться не могут.
         *
         * Единственная щель — страница, отрендеренная с серверными ошибками,
         * на которой скрипт догрузился позже. Её закрывает `clearServer()`
         * ниже: первый клиентский сабмит гасит серверные сообщения, прежде
         * чем нарисовать свои.
         *
         * Вариант «один контейнер на оба источника» отклонён: `x-show`
         * и `x-text` при инициализации затирают серверный текст — тот же
         * класс ошибки, что запрет `x-model` на контроле с `@selected(old())`.
         */
        errors: {},

        /** Сообщение над кнопкой: сеть, протухшая сессия, неразбираемый ответ. */
        formError: '',

        /** Гасились ли уже серверные сообщения этой страницы. */
        serverCleared: false,

        async submit(event) {
            if (this.sending) {
                return;
            }

            const form = event.target;

            this.sending = true;
            this.errors = {};
            this.formError = '';
            this.clearServer(form);

            try {
                const response = await fetch(form.action, {
                    method: 'POST',
                    // `FormData` со всей формы целиком: токен CSRF, honeypot
                    // и поля подбора запчасти уходят как есть. Ручная сборка
                    // полей разъехалась бы с разметкой на первом же
                    // добавленном поле — молча и только для тех, у кого
                    // JavaScript работает.
                    body: new FormData(form),
                    headers: {
                        // Обоих заголовков достаточно, чтобы сервер выбрал
                        // JSON-ветку ответа: развилка построена на
                        // `expectsJson()` (см. `LeadController::accepted()`).
                        Accept: 'application/json',
                        'X-Requested-With': 'XMLHttpRequest',
                    },
                });

                await this.handle(response, form);
            } catch (error) {
                // Сеть недоступна или запрос оборван. Единственный случай,
                // когда в консоль публичной страницы что-то пишется:
                // поток штатных событий там ни к чему.
                console.error('[lead-form] запрос не дошёл до сервера', error);
                this.formError = FALLBACK_MESSAGE;
            } finally {
                // Именно в `finally`: кнопка, оставшаяся заблокированной
                // после ошибки, выглядит как зависшая форма, и человек
                // уходит вместо повторной попытки.
                this.sending = false;
            }
        },

        async handle(response, form) {
            if (response.status === 419) {
                this.formError = EXPIRED_MESSAGE;

                return;
            }

            let payload;

            try {
                payload = await response.json();
            } catch (error) {
                // Сюда приезжает и HTML после неожиданного редиректа:
                // `fetch` по умолчанию следует за 302, и разбор страницы
                // как JSON падает здесь. Симптом «форма зависла» иначе
                // не диагностируется вообще.
                console.error('[lead-form] ответ не разобран как JSON', response.status, error);
                this.formError = FALLBACK_MESSAGE;

                return;
            }

            // 422 (валидация) и 429 (лимит по IP) разбираются ОДНОЙ веткой:
            // отказ лимитера отвечает в формате ошибок валидации намеренно,
            // чтобы человек за общим адресом увидел «попробуйте через
            // минуту» под полем «Телефон», а не страницу ошибки.
            if (response.status === 422 || response.status === 429) {
                this.showErrors(payload, form);

                return;
            }

            if (! response.ok) {
                this.formError = FALLBACK_MESSAGE;

                return;
            }

            form.reset();

            // Событие уходит наверх до `window`, где его слушает единственное
            // на страницу модальное окно (`x-ui.modal`). Текст берётся
            // с сервера: тот же, что печатается баннером на пути без
            // JavaScript.
            this.$dispatch('lead-accepted', { message: payload.message ?? '' });
        },

        showErrors(payload, form) {
            const errors = payload.errors ?? {};

            this.errors = Object.fromEntries(
                Object.entries(errors).map(([field, messages]) => [
                    field,
                    Array.isArray(messages) ? messages[0] : String(messages),
                ]),
            );

            if (Object.keys(this.errors).length === 0) {
                this.formError = payload.message ?? FALLBACK_MESSAGE;

                return;
            }

            // Фокус на первое поле с ошибкой: на длинной форме сообщение
            // может оказаться за пределами экрана, и «кнопка не работает»
            // — самая частая формулировка этой жалобы.
            const first = Object.keys(this.errors)[0];
            form.querySelector(`[name="${first}"]`)?.focus();
        },

        /**
         * Гасит серверные сообщения об ошибках, отрендеренные Blade.
         *
         * Делается один раз за жизнь страницы и только при клиентском
         * сабмите: на пути без JavaScript этот код не исполняется вовсе,
         * и трогать там нечего.
         */
        clearServer(form) {
            if (this.serverCleared) {
                return;
            }

            this.serverCleared = true;
            form.querySelectorAll('[data-server-error]').forEach((node) => node.remove());
        },
    };
}
