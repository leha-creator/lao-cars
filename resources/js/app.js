import Alpine from 'alpinejs';
import collapse from '@alpinejs/collapse';

import leadForm from './lead-form';
import photoLightbox from './photo-lightbox';

// Статические изображения вёрстки (логотип) попадают в манифест Vite через
// этот импорт, и только благодаря ему `Vite::asset()` находит их в шаблонах.
// Без строки шаблон падает исключением о ненайденном в манифесте файле —
// связь между «не собирается страница» и «забыт glob» не читается вообще.
//
// Логотип — часть вёрстки, а не редактируемый контент, поэтому он живёт
// здесь, а не в медиабиблиотеке: хеш в имени даёт вечный кеш и корректную
// инвалидацию при замене, чего файл в public/ не даёт.
// `eager: true` обязателен. Ленивый вариант из документации Laravel даёт
// динамические импорты, которые никто не вызывает, и rolldown (сборщик Vite 8)
// вырезает их вместе с ассетами — сборка при этом зелёная, а файла в манифесте
// нет. Симптом приходит не на сборке, а на первой же странице с логотипом.
import.meta.glob(['../images/**'], { eager: true });

// Alpine отвечает за локальную интерактивность публичной части: галереи
// автомобилей, фильтры каталога, поведение форм заявки. Полноценный фронтенд-
// фреймворк проекту не нужен — списки каталога рендерятся на сервере ради SEO.
//
// Панель Filament работает на собственной сборке Livewire и этот бандл не
// подключает: смешивать их не нужно.
window.Alpine = Alpine;

// Единственная регистрация `Alpine.data()` в проекте, и живёт она здесь
// вынужденно. Правило `RULES.md` запрещает регистрацию из `@push('scripts')`
// — пушнутый скрипт исполняется либо раньше этого модуля, либо уже после
// `Alpine.start()`, и оба варианта ломаются молча. Регистрация ДО старта,
// то есть в этом файле, отрабатывает всегда.
//
// Остальные компоненты публичных страниц по-прежнему пишутся инлайном
// в `x-data`: сюда уезжает только то, что в атрибут не помещается —
// обработчик отправки формы заявки с разбором четырёх кодов ответа
// и просмотр фотографии с зумом, перетаскиванием и ловушкой фокуса.
Alpine.data('leadForm', leadForm);
Alpine.data('photoLightbox', photoLightbox);

// `x-collapse` — раскрытие подробного описания услуги (веха 4.13).
// Плагин обязателен: НЕзарегистрированная директива Alpine не бросает
// ошибку и не пишет в консоль — она просто ничего не делает, и блок
// раскрывается рывком при полностью зелёной сборке. Регистрация идёт
// ДО `Alpine.start()` по той же причине, что и `Alpine.data()` выше.
Alpine.plugin(collapse);

Alpine.start();
