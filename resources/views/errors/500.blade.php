{{--
    Страница «внутренняя ошибка» (веха 4.11).

    Своего маршрута у файла нет: Laravel сам ищет `errors/{статус}.blade.php`.
    Шаблон рендерится при `APP_DEBUG=false`; с включённой отладкой на его
    месте показывается разбор исключения, и это правильно — на сервере
    разработчика нужен стек, а не вежливая фраза.

    ЭТА СТРАНИЦА НАМЕРЕННО НЕ СТОИТ НА ОБЩЕМ LAYOUT, и это главное про неё.

    Шапка (`x-site-header`) читает телефон из настроек, подвал
    (`x-site-footer`) — контакты, соцсети и текст гарантии. Оба идут
    в `Setting`, то есть в базу. Пятисотку же отдают ровно тогда, когда
    что-то уже сломано, и «упала база» — самая частая причина из всех.
    Layout здесь превратил бы одну ошибку в две: исключение внутри
    шаблона ошибки Laravel перехватить уже нечем, и посетитель получил бы
    пустой экран вместо объяснения. Проверять это надо запросом при
    недоступной базе, а не чтением шаблона: глазами зависимость не видна —
    она спрятана в конструкторах компонентов.

    Что страница себе позволяет и почему:

      - `@vite` и `Vite::asset` — чтение манифеста сборки с диска, без базы
        и без сети. Отсутствующий манифест ломает вообще все страницы сайта,
        то есть это не тот сбой, от которого пятисотка должна защищать;
      - `route()` — построение адреса по таблице маршрутов в памяти;
      - `config()` — конфиг приложения.

    Чего не позволяет: моделей, `Setting`, кеша, очереди, любых компонентов
    публичной части. Шапка сведена к логотипу-ссылке, подвала нет вовсе.

    Оформление тёмное и берётся из тех же токенов, что весь сайт:
    отдельной палитры здесь не заводится. Светлой секции нет намеренно —
    страница короткая, и `.theme-light` дал бы светлое пятно между тёмным
    верхом и краем экрана.
--}}
