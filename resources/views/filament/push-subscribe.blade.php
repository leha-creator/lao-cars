    и в шаблонах не упоминается вовсе. Незаполненный ключ тега не даёт,
    и скрипт по его отсутствию понимает, что push не сконфигурированы, —
    то же поведение, что у несконфигурированного Telegram вехи 3.7.

    Токен CSRF отсюда не печатается: Filament кладёт свой мета-тег сам,
    а второй такой же завёл бы дубль, где какой из двух прочитает скрипт,
    решал бы порядок в разметке.
