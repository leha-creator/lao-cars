@props(['service'])

{{--
    Подробное описание услуги, раскрываемое на месте (веха 4.13).

    ОТДЕЛЬНОЙ СТРАНИЦЫ УСЛУГИ НЕТ, и это прямой выбор заказчика. У `Service`
    есть и `slug`, и `#[RouteKey('slug')]` — роута нет, и он не появляется:
    `/services/{slug}` тянет за собой контроллер, шаблон, meta-теги,
    микроразметку, хлебные крошки и вопрос, что делать с позицией без
    подробного описания. `RouteKey` при этом остаётся на месте намеренно:
    решение обратимо, а триггер пересмотра назван — просьба дать ссылку
    на конкретную услугу или описание длиной больше экрана.

    ОБЛАСТЬ ALPINE ПРИХОДИТ СНАРУЖИ. Компонент рассчитывает на `x-data`
    с полем `open` у ближайшего предка — обёртки карточки. Своего `x-data`
    он не заводит: тогда кнопка и панель оказались бы в РАЗНЫХ областях
    при вызове из двух мест, а область Alpine — это поддерево DOM,
    а не элемент.

    БЕЗ СКРИПТА ТЕКСТ ОСТАЁТСЯ ВИДЕН, а не теряется: `x-show` скрывает
    элемент присвоением `display:none` из JavaScript, то есть при
    неработающем Alpine панель просто остаётся раскрытой. Это и есть нужная
    деградация.

    САМА КНОПКА при этом скрыта `x-cloak` — правило проекта «контрол,
    который без скрипта ничего не делает, прячется» (веха 4.6, панель
    фильтра статусов и карточка быстрого подбора). Без скрипта сворачивать
    нечего: текст и так раскрыт, а живая кнопка, не делающая ничего,
    хуже отсутствующей. Она же прячется и на те миллисекунды, пока Alpine
    не инициализировался, — иначе подпись успевает моргнуть.

    `x-collapse` требует плагина `@alpinejs/collapse` (подключён
    в `resources/js/app.js`). Незарегистрированная директива Alpine
    не бросает ошибку и не пишет в консоль — она просто ничего не делает.

    Пустое подробное описание не даёт кнопки вовсе: кнопка, открывающая
    пустоту, читается как поломка.
--}}
@if (filled($service->details))
    <button
        type="button"
        x-cloak
        x-on:click.prevent="open = ! open"
        x-bind:aria-expanded="open ? 'true' : 'false'"
        aria-expanded="true"
        aria-controls="service-details-{{ $service->getKey() }}"
        {{-- `relative` обязателен: в карточке с «растянутой» ссылкой
             псевдоэлемент `after:inset-0` накрывает всю площадь, и кнопка
             без собственного контекста наложения оказалась бы ПОД ним —
             нажималась бы ссылка, а не она. Позиционированные элементы
             без `z-index` рисуются в порядке документа, а кнопка идёт
             после ссылки. --}}
        class="relative mt-4 inline-flex items-center gap-2 text-sm font-medium text-accent transition-colors hover:text-accent-hover"
    >
        <span x-text="open ? 'Свернуть' : 'Подробнее'">Подробнее</span>

        {{-- Каретка из границ, а не иконка из набора `x-ui.icon`: шеврона
             в наборе нет, и заводить его ради одной кнопки значит добавить
             в набор рисунок, который больше нигде не нужен.

             Поворота НЕТ в постоянных классах, и это не мелочь: Alpine
             снимает только те классы, которые сам и поставил, — оставленный
             в постоянных `rotate-180` не снялся бы никогда, и каретка
             в закрытом состоянии смотрела бы вверх. Поймано глазами
             на приёмке, сборка при этом была зелёной. --}}
        <span
            aria-hidden="true"
            x-bind:class="open ? 'rotate-180' : ''"
            class="inline-block size-0 border-x-4 border-t-5 border-x-transparent border-t-current transition-transform duration-200"
        ></span>
    </button>

    <div
        id="service-details-{{ $service->getKey() }}"
        x-show="open"
        x-collapse
        class="overflow-hidden"
    >
        {{-- `whitespace-pre-line`: поле в админке многострочное, и абзацы,
             набранные заказчиком переносами, обязаны доехать до страницы.
             Разметку значение не хранит и хранить не будет — печатается оно
             экранированным, иначе это XSS через админку. --}}
        <p class="mt-4 max-w-3xl text-sm leading-[1.7] whitespace-pre-line text-ink-muted">{{ $service->details }}</p>
    </div>
@endif
