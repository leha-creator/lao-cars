@props([
    'title' => null,
    'eyebrow' => null,
    'intro' => null,
    'below' => null,
])

{{--
    Шапка внутренней страницы: надзаголовок, H1, вводный текст и место
    под навигацию по странице.

    Заведён вехой 4.1 вместе с четырьмя страницами разом — три копии
    одного и того же блока разъехались бы на первом же изменении ритма
    заголовков, а вехам 4.4 и 4.5 он достаётся готовым.

    Заголовок принимается двумя способами (веха 4.3). Строкой `title` —
    для простых случаев, как в вехе 4.1. Слотом — там, где внутри H1 есть
    акцентное слово: в каталоге это «Автомобили в наличии и <span>под
    заказ</span>», а строкой разметку не выразишь. Своя секция заголовка
    в шаблоне каталога была бы четвёртой копией того же блока — ровно
    того, ради чего компонент и заводился.

    Именованный слот `below` принесла веха 4.4: якорную навигацию
    по категориям прайса. Она обязана стоять под вводным текстом и внутри
    шапки, а не отдельной секцией под ней, — иначе между H1 и первым
    блоком прайса появляется вторая граница.

    Проверка основного слота идёт через `hasActualContent()`, а не через
    `isEmpty()`, и это не стилистика. С появлением именованного слота всё,
    что стоит между тегами компонента вне `<x-slot:below>`, попадает
    в `$slot`. Пробелы фреймворк обрезает сам, а HTML-комментарий — нет:
    в отличие от блейдовского, он доезжает до вывода. Один такой комментарий
    рядом со слотом сделал бы `isEmpty()` ложным, и H1 стал бы пустым
    МОЛЧА: тег в разметке есть, текста в нём нет, ошибок нет, а симптом
    («пропал заголовок») никак не наводит на причину. `hasActualContent()`
    вырезает комментарии и обрезает пробелы — ровно то, что здесь
    и требуется.

    Про сам этот комментарий: писать внутри блейдовского комментария его же
    открывающую или закрывающую последовательность нельзя. Парсер вложенность
    не понимает, и первая внутренняя закрывающая последовательность
    закрывает комментарий целиком — остаток текста уезжает в разметку
    страницы как есть. Ловушка не гипотетическая: ровно так этот файл
    и протёк на все страницы, пока сторож в тестах не показал утечку.

    Атрибуты с места вызова доезжают до `<section>` (веха 4.11): все четыре
    внутренние страницы светлые, и класс `theme-light` обязан оказаться
    на самой секции, а не на обёртке вокруг компонента — обёртка получила бы
    боковые поля страницы и оставила бы по краям тёмные полосы. Умолчания
    классов здесь не конфликтуют с передаваемым: `theme-light` — не утилита,
    и правило `RULES.md` про двойной размер к нему не относится.
--}}
<section {{ $attributes->class('border-b border-line px-5 pt-12 pb-10 lg:px-8 lg:pt-18 lg:pb-12') }}>
    <div class="mx-auto max-w-page">
        @if ($eyebrow !== null)
            <div class="mb-4 text-[13px] tracking-[0.2em] text-accent uppercase">{{ $eyebrow }}</div>
        @endif

        <h1 class="font-display text-3xl font-semibold lg:text-[38px]">{{ $slot->hasActualContent() ? $slot : $title }}</h1>

        {{-- Вступление проходит через ту же типографику, что и сноски
             блоков главной (веха 4.14): `text-pretty` как база плюс
             склейка хвоста неразрывными пробелами, потому что первая
             остаётся рекомендацией браузеру, а требование заказчика
             сформулировано числом слов. --}}
        @if ($intro !== null && $intro !== '')
            <p class="mt-5 max-w-2xl leading-relaxed text-ink-muted text-pretty">{{ \App\Support\Typography::tie($intro) }}</p>
        @endif

        {{-- Отступ задаёт компонент, а не вызывающая сторона: ритм шапки
             страницы — его ответственность, иначе вторая страница со слотом
             отступ подберёт заново и на глаз. --}}
        @if ($below !== null)
            <div class="mt-8">{{ $below }}</div>
        @endif
    </div>
</section>
