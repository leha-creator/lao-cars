{{--
    Абзац-сноска рядом с заголовком блока (веха 4.14).

    До неё на главной лежало СЕМЬ копий одного и того же
    `<p class="leading-[1.7] text-ink-muted lg:max-w-110 lg:text-right">`
    — семь мест, где надо не забыть и про `text-pretty`, и про склейку
    хвоста. Компонент делает и то и другое один раз.

    ЧТО ОН ДЕЛАЕТ С ТЕКСТОМ. Прогоняет его через `Typography::tie()`:
    склеивает хвост неразрывными пробелами, чтобы на последней строке
    не оставалось одинокое слово, и подтягивает предлоги к следующему
    слову. Обоснование, пределы длины и причина, по которой одного
    `text-pretty` не хватает, — в PHPDoc самого класса.

    Текст берётся ИЗ СЛОТА, а не из атрибута: так вызов читается как
    обычный абзац. Слот приходит объектом, поэтому приводится к строке
    явно — и только он: разметку внутри склеивать нельзя, склейка
    работает по словам текста и `<span>` в середине разнесла бы её.

    `text-pretty` остаётся вместе со склейкой, а не вместо неё: склейка
    отвечает за хвост, `text-pretty` — за всё остальное распределение
    слов по строкам, и одно другому не мешает.

    Умолчания классов перекрываются с места вызова через `$attributes`,
    как в `x-page-heading`. Ширина и выравнивание сюда НЕ ВХОДЯТ
    намеренно: `lg:max-w-110 lg:text-right` — это раскладка конкретного
    блока, а не свойство сноски, и в компоненте она молча навязала бы
    правое выравнивание сноскам, которым оно не нужно.
--}}
<p {{ $attributes->class('leading-[1.7] text-ink-muted text-pretty') }}>{{ \App\Support\Typography::tie((string) $slot) }}</p>
