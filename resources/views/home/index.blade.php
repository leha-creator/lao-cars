                     * изменении ширины окна: от неё зависит вся раскладка.
                     */
                    measure() {
                        this.deal();

                        this.travel = Math.max(0, this.$refs.track.scrollWidth - this.$refs.track.clientWidth);

                        this.pinned = window.matchMedia('(min-width: 1024px)').matches
