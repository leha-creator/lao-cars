                    /**
                     * Раскладка картотеки. Ширина карточки и ширина видимой
                     * полоски выводятся из ширины экрана и связаны одним
                     * уравнением: когда все карточки сложены, стопка занимает
                     * ровно ширину ленты, то есть последняя карточка открыта
                     * целиком, а каждая предыдущая показывает свою полоску.
                     *
                     * `(n - 1) * strip + card = room`
                     *
                     * Отсюда `strip`. Полоска уже 190px не опускается — в неё
                     * не помещается заголовок этапа, — и тогда ужимается
                     * карточка, а не полоска: нечитаемая подпись хуже
                     * маленького кадра. Порог замерен, а не выбран: на 170px
                     * «Выдача и поддержка» ложится в три строки и режется.
                     *
                     * Обе величины ставит скрипт, а не класс, и это ЛЕЧЕНИЕ
                     * прежнего дефекта, а не украшение: ширина карточки была
                     * задана `clamp(280px, 22vw, 360px)`, упиралась в потолок
                     * уже на 1640px, и выше него лента переставала расти
                     * вместе с экраном. Путь прокрутки схлопывался линейно:
