                     * Лента догоняет прокрутку, а не повторяет её щелчок
                     * в щелчок. Присваивание `scrollLeft` напрямую отдаёт
                     * ленте рывок колеса как есть: одно движение — один
                     * скачок на сто пикселей. Здесь между ними стоит
                     * интерполяция, и лента доезжает за несколько кадров.
                     *
                     * Петля останавливается, когда догнала: держать rAF
                     * вечно значит не давать заснуть вкладке, которую никто
                     * не трогает.
                     */
