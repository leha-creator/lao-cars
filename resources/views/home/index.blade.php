                        const track = this.$refs.track;
                        const cards = track.querySelectorAll('article');

                        if (cards.length < 2) {
                            this.stacked = false;

                            return;
                        }

                        // Боковое поле ленты вычитается ОДИН раз с каждой
                        // стороны и в смещение стопки не подставляется:
                        // браузер отсчитывает `sticky left` от контентного
                        // бокса прокручиваемой области, то есть добавляет
                        // это поле сам. Прибавленное второй раз, оно сдвигает
                        // всю стопку вправо, и последняя карточка перекрывает
                        // предпоследнюю ровно на его ширину — заметно только
