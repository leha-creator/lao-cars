{{--
    Тело юридического документа: заголовок, строка редакции и текст.

    Общий для политики и согласия — документов два, раскладка одна, и два
    шаблона с одинаковой разметкой разошлись бы на первой же правке.
    Ожидает `$title`, `$version`, `$effectiveOn` и `$body`; `title`
    и `description` страницы задаёт вызывающий шаблон.

    Страница светлая целиком. `theme-light` вешается на КАЖДУЮ секцию и на
    сам `x-page-heading`, а не на обёртку вокруг них: обёртка получила бы
    боковые поля страницы и оставила бы по краям тёмные полосы. То же
    решение и по той же причине принято на контактах.

    **Тело печатается в HTML без экранирования Blade — и это безопасно
    ровно потому, что оно уже прошло санитайзер.** Сервис страницы
    пропускает текст через `RichContentRenderer`, как того прямо требует
    шапка `Filament\Forms\Components\RichEditor`: значение поля — сырой
    HTML, его можно перехватить и отправить на бэкенд любым. Ограниченный
    набор инструментов на вкладке настроек этого не заменяет — тулбар живёт
    в браузере, а запрос уходит с любым телом. Брать `$body` в обход
    сервиса нельзя.

    `Typography` к телу НЕ применяется: он рассчитан на короткие текстовые
    настройки, а здесь на входе размеченный HTML.

    Оформление HTML из редактора задаётся классами на обёртке `.prose-legal`
    (стили — в `resources/css/app.css`). Плагин `@tailwindcss/typography`
    в проекте не подключён, и тянуть его ради двух страниц не нужно.
--}}
<x-page-heading eyebrow="Документы" :title="$title" class="theme-light" />

<section class="theme-light px-5 pt-12 pb-16 lg:px-8 lg:pb-20">
    <div class="mx-auto max-w-page">
        {{-- Редакция и дата — каждая половина пропадает отдельно:
             очищенное поле настройки не должно давать «Версия ,
             действует с». Обе пусты — строки нет вовсе. --}}
        @if ($version !== null || $effectiveOn !== null)
            <div class="mb-8 text-[13px] tracking-[0.1em] text-ink-muted uppercase">
                @if ($version !== null)
                    Редакция {{ $version }}@if ($effectiveOn !== null),@endif
                @endif

                @if ($effectiveOn !== null)
                    действует с {{ $effectiveOn }}
                @endif
            </div>
        @endif

        {{-- Блок без данных не рендерится вовсе — правило проекта.
             Пустой текст документа при этом уже записан в лог
             предупреждением: страница выглядит недоделанной, и связать
             её вид с очищенной настройкой иначе будет нечем. --}}
        @if ($body !== null)
            <div class="prose-legal max-w-3xl rounded-card border border-line bg-surface p-6 lg:p-10">
                {!! $body !!}
            </div>
        @endif
    </div>
</section>
