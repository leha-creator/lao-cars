{{--
    Политика обработки персональных данных (веха 4.17).

    Данные готовит `App\Services\PrivacyPageContent`: настройка
    `legal.privacy` — тело, версия и дата вступления в силу. Blade в базу
    не ходит.

    **Макета у страницы нет, и он ей не нужен.** Собрана по рецепту
    внутренней страницы из `docs/design-system.md` теми же кирпичами, что
    `/contacts`, у которой макета тоже не было: `x-page-heading` вместо
    фотографического хиро, карточка на `bg-surface` с обводкой `border-line`,
    светлая ветка палитры.

    Страница светлая целиком. `theme-light` вешается на КАЖДУЮ секцию и на
    сам `x-page-heading`, а не на обёртку вокруг них: обёртка получила бы
    боковые поля страницы и оставила бы по краям тёмные полосы. То же
    решение и по той же причине принято на контактах.

    **`x-lead-section` внизу нет, и это единственная такая страница сайта.**
    Форма заявки под текстом политики — это предложение оставить
    персональные данные прямо на странице, объясняющей, как их обрабатывают.
    Кнопку «Оставить заявку» в шапке это не ломает: она ведёт на `#lead-form`,
    якоря на странице нет, и браузер остаётся на месте.

    **Тело печатается через `{!! !!}`, то есть в HTML без экранирования
    Blade — и это безопасно ровно потому, что оно уже прошло санитайзер.**
    `PrivacyPageContent` пропускает текст через `RichContentRenderer`,
    как того прямо требует шапка `Filament\Forms\Components\RichEditor`:
    значение поля — сырой HTML, его можно перехватить и отправить на бэкенд
    любым, поэтому в Blade его печатают только через рендерер. Ограниченный
    набор инструментов на вкладке настроек этого не заменяет — тулбар живёт
    в браузере, а запрос уходит с любым телом. Печатать здесь `$body` без
    `{!! !!}` нельзя (на странице будут видны теги), а брать его в обход
    сервиса — тем более.

    `Typography` к телу НЕ применяется: он рассчитан на короткие текстовые
    настройки, а здесь на входе размеченный HTML.

    Оформление HTML из редактора задаётся классами на обёртке `.prose-legal`
    (стили — в `resources/css/app.css`). Плагин `@tailwindcss/typography`
    в проекте не подключён, и тянуть его ради одной страницы не нужно.
--}}
@extends('layouts.app')

