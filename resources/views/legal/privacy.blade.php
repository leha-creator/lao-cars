                 её вид с очищенной настройкой иначе будет нечем. --}}
            @if ($body !== null)
                <div class="prose-legal max-w-3xl rounded-card border border-line bg-surface p-6 lg:p-10">
                    {!! $body !!}
                </div>
            @endif
        </div>
