<?php

declare(strict_types=1);

namespace App\View\Components;

use App\Models\Service;
use Illuminate\Contracts\View\View;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Collection;
use Illuminate\View\Component;
use InvalidArgumentException;

/**
 * Форма заявки — один компонент на все формы сайта (веха 3.7).
 *
 * Четыре сценария из ТЗ различаются только параметрами: заявка
 * на конкретный автомобиль (`:source="$car"`), запись на услугу
 * (`:source="$service"`), выбор услуги из списка (`:services="$services"`,
 * веха 4.4) и общая форма без источника. Подбор запчасти добавляет поля
 * флагом `:parts="true"`.
 *
 * Четвёртый сценарий существует потому, что форма на странице автосервиса
 * одна, а позиций прайса семнадцать: статический `:source` здесь
 * не работает по устройству. Он добавлен ПАРАМЕТРОМ, а не четвёртой копией
 * формы, — по той же причине, по которой копий нет и у первых трёх.
 *
 * Отдельных форм на страницу нет намеренно: копии одной разметки разъедутся
 * на первом же изменении набора полей, а поле, добавленное в две формы
 * из трёх, теряет данные молча.
 *
 * Компонент снова только `<form>` — раскладки живут в `x-lead-section`
 * (веха 4.3). Триггер, названный вехой 4.2 дословно («третий вызов
 * с раскладкой — повод вынести обёртку в отдельный компонент»), сработал:
 * карточке автомобиля нужна форма внутри правой колонки — не полноширинная
 * секция с фоном и не центрированная карточка, а третья раскладка.
 * Добавлять третью ветку компоненту, у которого уже восемь параметров, —
 * ровно то, от чего веха 4.2 и предостерегала.
 *
 * Разделение проходит ВОКРУГ `<form>`. Инварианты вехи 3.7 внутри неё
 * не изменились ни на строку и после вехи 4.4: honeypot за пределами экрана,
 * отсутствие `page_url`, `old()` во всех полях, `maxlength="17"` на VIN.
 * Веха 4.4 добавила в форму только селект четвёртого сценария, и он подчинён
 * тем же правилам. Сторож тот же: `LeadStoreTest` и `SectionPagesTest`,
 * прошедшие без правок. Правка теста под новую вёрстку означала бы, что
 * сломано поведение, а не разметка.
 */
final class LeadForm extends Component
{
    /**
     * @param  ?string  $title  Заголовок над формой. `null` — не рендерится вовсе:
     *                          в двухколоночной раскладке `x-lead-section` заголовок
     *                          уже стоит в соседней колонке, и второй H2 подряд про одно
     *                          и то же ломает иерархию. Иерархия заголовков не оформление —
     *                          по ней ходят скринридеры и по ней страницу разбирает поисковик.
     * @param  ?Collection<int, Service>  $services  Опубликованные позиции прайса
     *                                               для селекта «Интересует». Взаимоисключающ с `$source`.
     */
    public function __construct(
        public ?Model $source = null,
        public ?string $title = null,
        public string $submit = 'Отправить заявку',
        public bool $parts = false,
        public ?Collection $services = null,
    ) {
        // Одновременная передача — ошибка разработчика, и падать она обязана
        // явно, на рендере. Молча отдать форму с двумя источниками означало бы
        // заявку, ушедшую не туда: скрытый `source_id` от `$source` и селект
        // с тем же именем в одной форме, где побеждает последний в разметке.
        // Симптом при этом появился бы у менеджера в списке заявок, а не
        // у того, кто это собрал.
        if ($source !== null && $services !== null) {
            throw new InvalidArgumentException(
                'x-lead-form: :source и :services взаимоисключающи — форма не может нести два источника заявки одновременно.',
            );
        }
    }

    /**
     * Показывать ли селект выбора услуги.
     *
     * Метод, а не выражение в шаблоне: условие нужно в двух местах —
     * у самого селекта и у сообщения об ошибке `source_id`, — и разъехаться
     * им нельзя. Пустая коллекция селекта не даёт: выпадающий список
     * из одного варианта «нужна консультация» ничего не выбирает.
     */
    public function hasServiceChoice(): bool
    {
        return $this->services !== null && $this->services->isNotEmpty();
    }

    /**
     * Алиас источника для скрытого поля формы.
     *
     * `getMorphClass()` отдаёт готовые `car` и `service` — ровно то, что
     * лежит в `leads.source_type`, потому что morph map включён
     * в `AppServiceProvider::boot()`. Второй словарь «класс → алиас»
     * здесь не нужен и разошёлся бы с первым.
     */
    public function sourceType(): ?string
    {
        return $this->source?->getMorphClass();
    }

    public function render(): View
    {
        return view('components.lead-form');
    }
}
