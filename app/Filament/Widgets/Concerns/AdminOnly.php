<?php

declare(strict_types=1);

namespace App\Filament\Widgets\Concerns;

/**
 * Виджет инфопанели, видимый только администратору.
 *
 * Виджет — не ресурс: политика к нему не применяется, и строгий режим
 * авторизации панели виджеты не закрывает. Штатный `Widget::canView()`
 * возвращает `true` всем — тот же случай, что `ManageSiteSettings::canAccess()`.
 * Проверка живёт здесь, в одном трейте, а не в восьми копиях.
 *
 * Сторож — `DashboardGuardTest`: он перебирает ВСЕ классы каталога
 * `Widgets/`, и новый виджет без этого трейта роняет набор. Состояние
 * сервера и посещаемость менеджеру не нужны, а версия кода и срок
 * сертификата — ещё и не его дело.
 */
trait AdminOnly
{
    public static function canView(): bool
    {
        return auth()->user()?->isAdmin() === true;
    }

    /**
     * То же решение под именем, которого ждёт справка.
     *
     * `HelpContent` решает, показывать ли статью, вызовом
     * `$gate::canAccess()` — у ресурсов и страниц метод есть, у виджетов
     * нет. Статья об инфопанели берёт ключом доступа виджет, и второй
     * матрицы прав ради неё не заводится.
     */
    public static function canAccess(): bool
    {
        return static::canView();
    }
}
