<?php

declare(strict_types=1);

namespace App\Filament\Actions;

use App\Filament\Pages\Help\Article;
use App\Support\Help\HelpLibrary;
use Filament\Actions\Action;
use Filament\Support\Icons\Heroicon;
use InvalidArgumentException;

/**
 * Кнопка «Справка» в шапке раздела панели — ссылка на статью о нём.
 *
 * Отдельный класс, а не копия четырёх строк в девяти шапках: правило
 * проекта про действия, живущие в нескольких местах (см. PHPDoc
 * `DeleteBrandAction`). Продублированное действие однажды обновится
 * только в одном месте — и заметить это можно, только открыв все девять.
 *
 * Раздел справки, до которого надо догадаться дойти, эквивалентен
 * отсутствию раздела: вопрос возникает в шапке списка, а не в боковом меню.
 */
final class HelpAction
{
    /**
     * Действие НЕ проверяет доступ к статье — и это не упущение.
     *
     * Видимость статьи спрашивается у того самого раздела, в шапке
     * которого стоит кнопка. Раз человек видит раздел, он видит и статью
     * о нём: привести в отказ эта ссылка физически не может. Проверка
     * «на всякий случай» здесь была бы вторым источником правды
     * о правах — ровно тем, чего решение про ключи доступа и избегает.
     */
    public static function make(string $slug): Action
    {
        if (HelpLibrary::find($slug) === null) {
            // Громко и сразу, а не тихой ссылкой в 404: опечатка в слаге
            // иначе доезжает до сотрудника, который нажал «Справка»
            // и получил «страница не найдена». Здесь же она валит шапку
            // раздела на первом открытии — то есть на прогоне тестов.
            throw new InvalidArgumentException("Статьи справки «{$slug}» нет в реестре.");
        }

        return Action::make('help')
            ->label('Справка')
            ->icon(Heroicon::OutlinedQuestionMarkCircle)
            ->color('gray')
            ->url(Article::getUrl(['article' => $slug]));
    }
}
