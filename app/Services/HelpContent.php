<?php

declare(strict_types=1);

namespace App\Services;

use App\Support\Help\HelpArticle;
use App\Support\Help\HelpLibrary;
use App\Support\Help\HelpSection;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\HtmlString;
use Illuminate\Support\Str;

/**
 * Справка в панели: что показать сотруднику и во что превратить текст.
 *
 * Сервис без состояния и без `Request` — правило `ARCHITECTURE.md`.
 * Проверяется целиком без HTTP, кроме `canAccess()`, которому нужен
 * аутентифицированный пользователь.
 *
 * # Почему `canAccess()` зовётся из сервиса
 *
 * Формально это обращение к presentation-классу Filament из слоя сервисов,
 * и это ОСОЗНАННОЕ исключение — записанное здесь, потому что без записи
 * его «поправят» обратно.
 *
 * Видимость статьи спрашивается у того раздела, который она описывает
 * (поле `gate` в реестре). Второй матрицы прав не заводится: список ролей
 * в реестре разошёлся бы с политиками при первом же изменении прав,
 * и разошёлся бы в худшую сторону — статья про настройки осталась бы
 * видна менеджеру, который в настройки уже не ходит. Побочное следствие
 * приятное: кнопка «Справка» в шапке раздела физически не может привести
 * в отказ — раз человек видит раздел, он видит и статью о нём.
 *
 * Альтернативы рассмотрены и отклонены:
 *
 * - **фильтрация в самих страницах** — она нужна и странице-списку,
 *   и странице статьи, то есть переехала бы в общий трейт: тот же код
 *   слоем выше и без возможности проверить его без HTTP;
 * - **пара «действие + модель» и `Gate::allows()`** — чисто, но у страницы
 *   настроек сайта модели нет вовсе, и вместо одного вида ключа
 *   появились бы два.
 *
 * Этот класс — единственное место, знающее и «что есть», и «кому
 * показывать». Ровно так же устроен `LeadNotifier`, знающий, кому уходит
 * заявка.
 */
final class HelpContent
{
    /**
     * Статьи раздела, видимые текущему сотруднику.
     *
     * @return list<HelpArticle>
     */
    public function visible(HelpSection $section): array
    {
        return array_values(array_filter(
            HelpLibrary::inSection($section),
            fn (HelpArticle $article): bool => $this->isVisible($article),
        ));
    }

    /**
     * Видна ли статья текущему сотруднику.
     *
     * Ключ доступа не задан — статья общая. Задан — ответ даёт сам раздел:
     * `Resource::canAccess()` и `Page::canAccess()` есть оба и оба
     * статические.
     */
    public function isVisible(HelpArticle $article): bool
    {
        if ($article->gate === null) {
            return true;
        }

        /** @var callable(): bool $gate */
        $gate = [$article->gate, 'canAccess'];

        return $gate() === true;
    }

    /**
     * Текст статьи, превращённый в HTML.
     *
     * Файла нет — возвращается `null`, а не бросается исключение
     * и не зовётся `abort()`: HTTP-кодами занимается страница, сервис
     * про HTTP не знает (правило `ARCHITECTURE.md`).
     *
     * # Почему сняты умолчания конвертера
     *
     * `Str::markdown()` — это `GithubFlavoredMarkdownConverter`, а его
     * умолчания — `html_input => allow` и `allow_unsafe_links => true`.
     * Здесь они сняты, хотя сегодня файлы приходят из репозитория
     * и вектора нет: защита ставится не от сегодняшнего источника,
     * а от завтрашнего. Если статьи однажды переедут в базу (а триггер
     * назван — заказчик просит вести собственные регламенты), рендер
     * уже будет безопасным, и никто не вспомнит, что его надо было
     * ужесточить.
     *
     * Побочная польза: статьи остаются простым markdown-ом и переносимы
     * куда угодно. Понадобился HTML в статье — это сигнал завести
     * Blade-фрагмент, а не ослабить конвертер.
     *
     * Готовый HTML не кешируется намеренно: пятнадцать коротких файлов,
     * разбор одного — единицы миллисекунд на внутренней странице для трёх
     * человек. Кеш добавил бы ключ, инвалидацию по времени файла и класс
     * ошибок «поправил статью, а на экране старая». Триггер пересмотра:
     * справка выросла до сотни статей или в неё пришли изображения.
     */
    public function render(HelpArticle $article): ?HtmlString
    {
        $path = resource_path("help/{$article->file()}");

        if (! is_file($path)) {
            // Единственный отказ раздела, который снаружи выглядит как
            // «справка поломалась»: в реестре статья есть, в списке она
            // есть, а открыть нельзя. Без записи в лог он неразрешим.
            Log::warning('[Справка] у статьи пропал файл', [
                'slug' => $article->slug,
                'file' => $article->file(),
            ]);

            return null;
        }

        return new HtmlString(Str::markdown((string) file_get_contents($path), [
            'html_input' => 'strip',
            'allow_unsafe_links' => false,
        ]));
    }
}
