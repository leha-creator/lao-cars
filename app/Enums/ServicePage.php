<?php

declare(strict_types=1);

namespace App\Enums;

use App\Enums\Concerns\HasLabels;
use Filament\Support\Contracts\HasLabel;

/**
 * Публичная страница, на которой выводится категория услуг.
 *
 * Заведён вехой 4.13 вместе со справочником категорий и отвечает
 * на вопрос «где эта категория показывается». До него принадлежность
 * странице выводилась из ИМЕНИ категории: `/parts` отбирала позиции
 * по кейсу `ServiceCategory::Parts`, то есть по константе языка.
 * С редактируемым справочником такой отбор — гарантированный молчаливый
 * отказ: переименованная или удалённая категория оставляет посадочную
 * страницу с ответом 200, вступлением и формой, но без единого блока,
 * и заметить это снаружи некому.
 *
 * Енам, а не булево `is_parts`: колонка-переключатель читается как
 * «да/нет» и не переживёт третьей страницы, а `page` отвечает на тот
 * вопрос, который на самом деле задан.
 */
enum ServicePage: string implements HasLabel
{
    use HasLabels;

    case Services = 'services';
    case Parts = 'parts';

    public function label(): string
    {
        return match ($this) {
            self::Services => 'Автосервис',
            self::Parts => 'Запчасти',
        };
    }

    /**
     * Запчасти живут на своей посадочной странице, остальные категории —
     * блоками на странице автосервиса.
     *
     * Метод переехал сюда из `ServiceCategory` вместе с вехой 4.13:
     * вопрос «это запчасти?» теперь про страницу, а не про категорию.
     */
    public function isParts(): bool
    {
        return $this === self::Parts;
    }
}
