<?php

declare(strict_types=1);

namespace App\Http\Controllers;

use App\Enums\ServiceCategory;
use App\Models\Service;
use App\Models\Setting;
use Illuminate\Contracts\View\View;
use Illuminate\Support\Facades\Log;

/**
 * Посадочная страница подбора запчастей.
 *
 * Заглушки вехи 4.1 здесь больше нет: веха 4.4 добавила категории
 * запчастей. Заголовок, вводный текст и условия поставки по-прежнему
 * приходят из настроек, форма подбора — прежняя.
 *
 * Сервиса-прослойки у этой страницы нет НАМЕРЕННО, и это не забывчивость
 * в паре с `ServicesPageContent`. Здесь один запрос и три текстовых ключа,
 * то есть прослойка была бы пустым файлом, который только переадресует
 * вызов; `ARCHITECTURE.md` приводит РОВНО этот запрос
 * (`Service::inCategory(ServiceCategory::Parts)`) примером допустимого
 * чтения из контроллера. Граница названа там же: сервис появляется, когда
 * данные надо приводить к форме, прежде чем отдать их в Blade. У страницы
 * автосервиса это так (группировка по категориям, отсев пустых, две
 * настройки-объекта, нормализация репитера), у этой — нет.
 *
 * Настройки читает контроллер и передаёт готовыми — правило «Blade
 * не ходит в БД». Исключение сделано только для шапки и подвала
 * (см. PHPDoc `SiteHeader`) и на страницы не распространяется.
 *
 * Форма здесь — тот же `x-lead-form`, но с флагом `parts`: он добавляет
 * марку, модель и VIN, по которым `Lead::isPartsRequest()` отличает заявку
 * на подбор от остальных. Флаг легко потерять при правке шаблона, поэтому
 * на него стоит отдельный тест. Источник заявки форма НЕ проставляет:
 * заявку на подбор отличают поля автомобиля, а категория без артикула
 * менеджеру не добавляет ничего — он всё равно идёт к поставщику по VIN.
 */
final class PartsController extends Controller
{
    public function index(): View
    {
        $categories = Service::query()
            ->inCategory(ServiceCategory::Parts)
            ->published()
            ->ordered()
            ->get();

        if ($categories->isEmpty()) {
            // WARN на каждый рендер — по тому же основанию, что у пустого
            // прайса автосервиса и пустой подборки главной: это
            // конфигурационная ошибка, которая чинится один раз в админке,
            // а посадочная без категорий выглядит недоделанной. Снаружи она
            // при этом отдаёт 200, и заметить причину больше нечем.
            Log::warning('[Запчасти] в категории «Запчасти» нет ни одной опубликованной позиции', [
                'hint' => 'опубликуйте позиции в разделе «Услуги и запчасти» админки',
            ]);
        }

        return view('parts.index', [
            // Фолбэк через второй аргумент `Setting::get()` срабатывает только
            // на отсутствующий ключ, а форма настроек пишет пустое значение
            // как есть — «очистить блок» там рабочий сценарий. Без проверки
            // на пустоту очищенный заголовок давал бы пустой H1 и заголовок
            // документа из одного тире: страница выглядела бы сломанной
            // при живой настройке и без единой ошибки в логе. Парная
            // нормализация — в `ServicesPageContent::build()`.
            'title' => self::heading(Setting::get('parts_page.intro_title')),
            'intro' => Setting::get('parts_page.intro_text'),
            'deliveryTerms' => Setting::get('parts_page.delivery_terms'),
            'categories' => $categories,
        ]);
    }

    /**
     * Заголовок страницы: непустая настройка или умолчание.
     *
     * Проверка пустоты строгая, а не `empty()` — правило `RULES.md`.
     */
    private static function heading(mixed $value): string
    {
        $title = is_scalar($value) ? trim((string) $value) : '';

        return $title === '' ? 'Запчасти' : $title;
    }
}
