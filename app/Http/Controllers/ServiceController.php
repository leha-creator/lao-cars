<?php

declare(strict_types=1);

namespace App\Http\Controllers;

use App\Services\ServicesPageContent;
use Illuminate\Contracts\View\View;

/**
 * Страница автосервиса.
 *
 * Заглушки вехи 4.1 здесь больше нет: веха 4.4 принесла блоки по категориям
 * (ТО и ремонт, шиномонтаж, детейлинг, доп. сервисы) с прайсом, оговорку
 * о ценах, блок «почему сюда» и выбор конкретной услуги в форме записи.
 *
 * Контроллер тонкий намеренно: данные собирает `ServicesPageContent`, а не
 * этот метод. Соблазн «упростить» сервис обратно сюда возникает у каждого,
 * кто открывает файл из трёх строк, поэтому причина записана явно —
 * группировка позиций по категориям, отсев пустых категорий, две
 * настройки-объекта разной формы и нормализация репитера. Граница названа
 * `ARCHITECTURE.md`: если данные надо приводить к форме, прежде чем отдать
 * их в Blade, это сервис, даже если запрос один. У соседнего
 * `PartsController` её нет и быть не должно — там как раз один запрос
 * и три текстовых ключа.
 *
 * Сервис приходит через контейнер, а не через `new`: правило
 * `ARCHITECTURE.md`, без него его не подменить в тесте.
 */
final class ServiceController extends Controller
{
    public function index(ServicesPageContent $content): View
    {
        return view('services.index', $content->build());
    }
}
