<?php

declare(strict_types=1);

namespace App\Http\Controllers;

use Symfony\Component\HttpFoundation\BinaryFileResponse;

/**
 * Снимок экрана для статьи справки (веха 4.15).
 *
 * Раздаёт один PNG из `resources/help/screenshots/` — папки, лежащей
 * ВНЕ веб-корня. Отсюда и весь этот класс: положи файлы в `public/`,
 * и раздачи не понадобилось бы вовсе.
 *
 * # Почему снимки не в `public/`
 *
 * Сегодня сняты настройки контактов — телефон, адрес и часы работы,
 * то есть данные, которые и так напечатаны на публичной странице сайта.
 * Завтра снимут экран «Заявки», а это телефоны клиентов.
 *
 * Правило «не снимай персональные данные» в регламенте написано
 * и действует ровно до первого человека, который его не прочитал.
 * Папка, которую веб-сервер физически не читает, держит то же свойство
 * без правила и без дисциплины.
 *
 * Это тот же ход мысли, что записан в PHPDoc `App\Services\HelpContent`
 * про снятые умолчания конвертера markdown: защита ставится не от
 * сегодняшнего источника, а от завтрашнего — потому что завтра никто
 * не вспомнит, что её надо было поставить.
 *
 * # Почему пропавший снимок не пишется в лог
 *
 * Пропавший файл СТАТЬИ пишется в `WARN` — основание в `HelpContent`:
 * в реестре статья есть, в списке она есть, а открыть нельзя, и снаружи
 * это выглядит как «справка поломалась».
 *
 * У снимка иначе, по двум причинам. Первая: расхождение текста статей
 * и папки со снимками ловится ДО коммита сторожами `HelpTest` —
 * ссылка без файла и файл без ссылки роняют тесты, то есть довезти
 * такое состояние до продакшена нельзя. Вторая: этот адрес достижим
 * руками, и любой вошедший сотрудник может набрать несуществующее имя.
 * `WARN` на это — шум того же класса, что отказы авторизации и 404
 * на подобранный слаг статьи, которые проект намеренно не пишет
 * (см. PHPDoc `App\Policies\AdminOnlyPolicy` и `Help\Article::article()`).
 *
 * **Условие обратимости названо явно:** если сторожа снимков из
 * `HelpTest` когда-нибудь снимут — `WARN` возвращается вместе с ними.
 * Без этой фразы решение читается как забывчивость.
 */
final class HelpScreenshotController extends Controller
{
    /**
     * Разрешённая форма имени файла.
     *
     * Строчные латинские буквы, цифры и дефис плюс расширение `.png`.
     * Ни точек, ни слешей, ни процентов — то есть выйти за пределы
     * папки этим именем нельзя в принципе.
     */
    private const NAME_PATTERN = '/^[a-z0-9-]+\.png$/';

    public function __invoke(string $name): BinaryFileResponse
    {
        // Порядок проверок важен: форма имени идёт ПЕРЕД любым
        // обращением к диску. `is_file('../../.env')` вернёт правду,
        // и проверка существования, поставленная первой, пропустила бы
        // чтение произвольного файла аутентифицированным сотрудником.
        abort_unless(preg_match(self::NAME_PATTERN, $name) === 1, 404);

        // `basename()` поверх уже проверенного имени — не «на всякий
        // случай». Стоит она одну строку, а цена пропуска — чтение
        // чужого файла; та же логика двойной проверки, по которой адрес
        // карты проверяется и правилом формы, и `App\Support\MapEmbed`
        // на выводе. Одна проверка — это проверка, которую однажды
        // ослабят, не заметив второго потребителя.
        $path = resource_path('help/screenshots/'.basename($name));

        abort_unless(is_file($path), 404);

        $response = response()->file($path, [
            // `no-cache`, а не длинный `max-age`: это «храни, но спроси
            // перед показом». Переснятый снимок обязан появиться сразу,
            // иначе регламент пересъёмки упирается в кеш браузера,
            // и статья неделю показывает экран, которого уже нет.
            // `must-revalidate` здесь не подошёл бы: без `max-age`
            // свежесть считается эвристикой по `Last-Modified`,
            // и давно снятый файл получил бы длинный срок жизни —
            // ровно то, что мы предотвращаем.
            'Cache-Control' => 'no-cache',
        ]);

        // `setPrivate()` ОБЯЗАТЕЛЕН, и он не дубль заголовка выше.
        //
        // Найдено на приёмке: ответ уходил с `Cache-Control: no-cache,
        // public` при том, что в массиве заголовков было написано
        // `private, no-cache`. Причина — конструктор
        // `Symfony\Component\HttpFoundation\BinaryFileResponse`:
        // у него параметр `$public` по умолчанию `true`, и он зовёт
        // `setPublic()` ПОСЛЕ применения переданных заголовков.
        // А `setPublic()` не просто добавляет `public` — он удаляет
        // `private`.
        //
        // Симптом молчаливый: картинка отдаётся, страница выглядит
        // правильно, и заметить подмену можно только прочитав заголовки
        // ответа. Цена — снимок админки, который разрешено сложить
        // в ОБЩИЙ кеш (прокси провайдера, корпоративный кеш), то есть
        // ровно та утечка, ради предотвращения которой файлы и лежат
        // вне `public/`.
        $response->setPrivate();

        // `Last-Modified` из времени файла конструктор проставляет сам
        // (`$autoLastModified` там тоже `true` по умолчанию), поэтому
        // отдельного вызова здесь нет. Ответ 304 при этом не собирается:
        // условная выдача потребовала бы разбирать `If-Modified-Since`
        // руками, а речь о шести файлах до 300 КБ на внутренней странице
        // для трёх человек. Заголовок остаётся честной меткой времени
        // съёмки — по нему видно, когда экран переснимали.
        return $response;
    }
}
