<?php

declare(strict_types=1);

namespace App\Http\Controllers;

use App\Services\AboutPageContent;
use Illuminate\Contracts\View\View;

/**
 * Страница «О компании» (веха 4.5).
 *
 * Заглушки вехи 4.1 у этой страницы не было вовсе: до вехи 4.5 не было
 * и роута, а пункт «О компании» в подвале просто не выводился —
 * `SiteMenu::links()` отсеивает пункты без зарегистрированного роута.
 * С появлением этой строки он появляется там сам, без единой правки
 * `SiteMenu::FOOTER`.
 *
 * Контроллер тонкий намеренно: данные собирает `AboutPageContent`, а не
 * этот метод. Причина записана явно, потому что соседняя пара
 * `ServiceController` / `PartsController` разведена по обе стороны той же
 * границы, и без объяснения третий случай читается как произвол.
 *
 * **Почему сервис здесь есть.** Источников три — группа настроек
 * `about_page.*`, опубликованные сотрудники и опубликованные отзывы, — и
 * два из них требуют приведения к форме до Blade: репитер истории при
 * удалении всех элементов приходит `null`, а не `[]`, а миссия — это
 * настройка-объект, у которой оба поля могут оказаться пустыми. Плюс
 * `with('media')` у обеих выборок, без которого сетка команды даёт N+1.
 * Граница названа в `ARCHITECTURE.md` дословно: «если данные надо
 * приводить к форме, прежде чем отдать их в Blade, это сервис, даже если
 * запрос один». У `PartsController` не так — там один запрос и три
 * текстовых ключа, — и потому у него сервиса нет и быть не должно.
 *
 * Сервис приходит через контейнер, а не через `new`: правило
 * `ARCHITECTURE.md`, без него его не подменить в тесте.
 */
final class AboutController extends Controller
{
    public function index(AboutPageContent $content): View
    {
        return view('about.index', $content->build());
    }
}
