<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Models\Setting;
use App\Support\Legal\LeadIntake;
use App\Support\Legal\PrivacyPolicy;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Log;

/**
 * Установка юридических настроек на проде (веха 4.17).
 *
 * **Зачем нужна отдельная команда.** На прод сиды не выкатываются:
 * `deploy/deploy.sh` выполняет `php artisan migrate --force` и ничего
 * больше. Без этого шага прод получил бы страницу `/privacy` без текста —
 * то есть опубликованный пустой юридический документ. Прецедент разового
 * шага на проде в проекте уже есть и записан в роадмапе вехой 7.1:
 * `php artisan laocars:make-admin`.
 *
 * **Почему не миграция данных.** Докблок миграции
 * `2026_08_19_120000_replace_work_hours_with_schedule_setting` формулирует
 * правило прямо: классы приложения в миграциях не упоминаются, миграция
 * обязана исполняться на схеме своего дня и пережить переименование любого
 * класса. Значит текст политики пришлось бы скопировать в неё целиком —
 * несколько килобайт вторым источником правды, который разойдётся
 * с `PrivacyPolicy` на первой же правке.
 *
 * **Идемпотентность — главное требование.** Существующее значение
 * не трогается НИКОГДА. Повторный запуск после того, как юрист поправил
 * текст в панели, обязан ничего не сделать: команда, которая «обновляет»
 * настройки, при следующем деплое затрёт документ обратно на заглушку
 * с незаполненными реквизитами — молча и на живом сайте. По этой же
 * причине запускать на проде `db:seed` нельзя: `SiteSettingSeeder::run()`
 * пишет `Setting::set()` по каждому ключу без проверки.
 */
final class InstallLegalSettingsCommand extends Command
{
    protected $signature = 'laocars:install-legal-settings';

    protected $description = 'Создать недостающие настройки политики обработки персональных данных (существующие не трогает)';

    public function handle(): int
    {
        $created = [];

        foreach ($this->settings() as $key => $value) {
            // `Setting::get()` с умолчанием-сентинелом, а не `filled()`:
            // значение `false` (выключенный приём заявок) — полноценная
            // настройка, и проверка на «пусто» посчитала бы её отсутствующей
            // и переписывала бы при каждом запуске.
            if (Setting::get($key, $this) !== $this) {
                $this->line("  {$key} — уже есть, пропущен");

                continue;
            }

            Setting::set($key, $value);
            $created[] = $key;

            $this->info("  {$key} — создан");
        }

        $this->newLine();
        $this->info('[install-legal-settings] создано: '.count($created).', пропущено: '.(count($this->settings()) - count($created)));

        if ($created !== []) {
            // Команду запускают на проде руками, и след о том, что и когда
            // она завела, нужен именно там: вывод в консоль после закрытия
            // сессии не восстановить.
            Log::info('[Политика] установлены юридические настройки', ['created' => $created]);
        }

        $this->newLine();
        $this->warn('Приём заявок остаётся ВЫКЛЮЧЕННЫМ. Включите его в панели («Настройки сайта → Персональные данные») после того, как уведомление об обработке персональных данных подано в Роскомнадзор.');
        $this->warn('До этого проверьте текст политики: реквизиты оператора помечены двойными квадратными скобками и должны быть заменены.');

        return self::SUCCESS;
    }

    /**
     * Настройки, которые обязаны существовать на проде.
     *
     * @return array<string, mixed>
     */
    private function settings(): array
    {
        return [
            PrivacyPolicy::SETTING_KEY => PrivacyPolicy::defaultSetting(),

            // Явное `false`, хотя умолчание в коде тоже «выключено».
            // Строка в базе нужна затем, чтобы тумблер в панели имел что
            // показывать и переключать: без неё администратор видит
            // выключенный переключатель и не может понять, настройка это
            // или отсутствие настройки.
            LeadIntake::SETTING_KEY => false,
        ];
    }
}
