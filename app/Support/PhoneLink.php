<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Телефон компании в виде адреса ссылки `tel:` (веха 4.5).
 *
 * Живёт в `app/Support/` по тому же признаку, что `SocialLinks` и `SiteMenu`:
 * преобразование понадобилось третьему потребителю. Пока копий было две —
 * `SiteHeader` и `SiteFooter`, соседние классы одного слоя, — дубль терпелся
 * как их общая деталь. Страница контактов стала третьей, и нормализация
 * номера перестала быть деталью двух компонентов: это общее знание вёрстки
 * о том, как из «+7 495 123-45-67» получается адрес ссылки.
 *
 * Вынос обязан был забрать ОБЕ прежние копии, а не встать рядом с ними.
 * Две реализации одного правила расходятся молча: симптом — номер, который
 * набирается из подвала и не набирается из шапки, — читается как поломка
 * телефона, а не как расхождение двух `preg_replace`.
 */
final class PhoneLink
{
    /**
     * Адрес для `tel:` — без пробелов, скобок и дефисов.
     *
     * Пустой результат — это `null`, а не пустая строка, и проверка идёт
     * ПОСЛЕ чистки. Номер из одних скобок («( ) —») даёт после `preg_replace`
     * пустую строку, а `href="tel:"` выглядит рабочей ссылкой и ведёт
     * в никуда: звонилка открывается с пустым полем. Отсутствующая ссылка
     * честнее — вызывающая сторона умеет не рендерить блок вовсе.
     */
    public static function href(?string $phone): ?string
    {
        if ($phone === null || $phone === '') {
            return null;
        }

        $digits = preg_replace('/[^\d+]/', '', $phone) ?? '';

        return $digits === '' || $digits === '+' ? null : $digits;
    }
}
