<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Длина префикса значения характеристики, по которому построен индекс
 * фильтра каталога (веха 3.6).
 *
 * Обычный индекс `(car_attribute_id, value)` завести нельзя: запись
 * b-tree ограничена 2704 байтами, а `value` — `text`, куда вставленная
 * копипастом комплектация ляжет целиком и уронит `INSERT`. Частичный
 * индекс `WHERE length(value) <= 64` не спасает: планировщик не выводит
 * этот предикат из условия `value = 'Седан'` и индекс не возьмёт.
 * Поэтому индекс строится по выражению `left(value, 64)`, а запрос идёт
 * двумя условиями — префикс сужает по индексу, точное равенство
 * подтверждает совпадение.
 *
 * Значением пользуются миграция, `CatalogFilter` и тест-сторож, поэтому
 * оно живёт в `app/Support/` — тем же приёмом, что `ThumbnailPath`
 * и `MediaSettingKeys`. Длину нельзя вынести в конфиг: конфиг меняется
 * правкой файла, а индекс — только новой миграцией, и расхождение будет
 * молчаливым.
 */
final class AttributeFilterIndex
{
    public const int PREFIX_LENGTH = 64;

    /**
     * Префикс значения ровно в том виде, в каком его считает PostgreSQL.
     *
     * `mb_substr()`, а не `substr()`: `left()` в PostgreSQL режет
     * **символы**, `substr()` в PHP — **байты**. На кириллице (2 байта
     * на символ) `substr($value, 0, 64)` даёт другую строку, а иногда
     * и обрубок посреди символа: условие перестаёт совпадать с индексом,
     * и фильтр по «Кроссовер» тихо перестаёт находить кроссоверы.
     * Ошибка стоит не падения, а неверной выдачи.
     */
    public static function prefix(string $value): string
    {
        return mb_substr($value, 0, self::PREFIX_LENGTH);
    }
}
