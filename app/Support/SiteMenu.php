<?php

declare(strict_types=1);

namespace App\Support;

use Illuminate\Support\Facades\Route;

/**
 * Состав навигации сайта — единственный источник правды (веха 4.1).
 *
 * Живёт в `app/Support/`, а не константой на компоненте шапки, по правилу
 * зависимостей из `ARCHITECTURE.md`: список нужен и шапке, и подвалу, и ни
 * один из них не должен знать о другом. Тот же приём, что и в
 * `MediaSettingKeys` и `ThumbnailPath`.
 *
 * Второй список завести проще, чем кажется, — и он разойдётся с первым на
 * первом же новом разделе. Ровно по этой причине веха 3.7 сделала одну форму
 * заявки на три сценария вместо трёх копий.
 *
 * **Состав меню берётся отсюда, а не из макета.** В шапке макета — «Каталог ·
 * Услуги · Блог · Контакты», и это устаревший вариант: блог из проекта снят
 * целиком, а его место заняли «Сервис» и «Запчасти» (решение зафиксировано
 * в `DESCRIPTION.md` и в разделе «Ориентиры из макета» роадмапа). При сверке
 * вёрстки с макетом меню «поправят» обратно, если не знать этого.
 *
 * **Подписи пунктов расходятся с названиями разделов, и это намеренно.**
 * Каталог подписан «Автомобили», автосервис — «Сервис»: заказчик на
 * демонстрации 11.08.2026 переименовал пункты меню, а не разделы (по сервису
 * ответ пришёл позже, 13.08.2026 — до него правка сознательно не делалась).
 * Поэтому заголовок страницы `/catalog`, надзаголовок списка, хлебная крошка
 * карточки авто и микроразметка `CarStructuredData::breadcrumbs()` не тронуты —
 * крошка в разметке и крошка в JSON-LD обязаны совпадать, и правка одной из них
 * ломает пару. По той же причине не тронуты H1 страницы `/services`
 * (`services_page.intro_title`, настройка в панели), вкладка админки
 * «Автосервис и запчасти» и плашка направления на главной. Выглядит это как
 * забытые места; это не они.
 */
final class SiteMenu
{
    /**
     * Подписи разделов по именам роутов.
     *
     * @var array<string, string>
     */
    private const array LABELS = [
        'catalog.index' => 'Автомобили',
        'services.index' => 'Сервис',
        'parts.index' => 'Запчасти',
        'contacts.index' => 'Контакты',
        'about.index' => 'О компании',
    ];

    /**
     * Закреплённое меню шапки — пять пунктов в этом порядке.
     *
     * **Пунктов было четыре — ровно столько, сколько фиксировало ТЗ.**
     * «О компании» добавлена пятой по прямому требованию заказчика
     * на демонстрации 11.08.2026, и позицию выбрал он же: рассматривал
     * вслух два места («либо после запчастей, либо после контактов») и
     * остановился на «после запчастей». Контакты уехали на пятую позицию.
     * Из ТЗ этот пункт не следует, и вернуть его к четырём «по ТЗ» —
     * значит отменить решение заказчика, а не исправить расхождение.
     *
     * **Пять — это предел, и упирается он в вёрстку, а не во вкус.**
     * Десктопное меню (`site-header.blade.php`) делит одну строку
     * с логотипом, телефоном текстом и кнопкой заявки, объявлено
     * `whitespace-nowrap` и права на перенос не имеет. Узкое место —
     * диапазон 1024–1280px: на `lg` горизонтальное меню уже показано,
     * а увеличенный зазор `xl:gap-7` ещё не включился.
     *
     * Замерено вехой 4.5 в браузере: свободного места между меню и правой
     * группой остаётся 60px на 1024px, 124px на 1152px и 180px на 1280px.
     * Пятый пункт («О компании», 78px) помещается везде; шестой — вместе
     * с зазором это около 100px — на 1024px уже не поместится, и меню
     * поедет под кнопку заявки. Мобильному меню число пунктов безразлично:
     * там вертикальный список в оверлее `fixed inset-0`.
     *
     * @var list<string>
     */
    private const array HEADER = [
        'catalog.index',
        'services.index',
        'parts.index',
        'about.index',
        'contacts.index',
    ];

    /**
     * Подвал и шапка совпадают по составу с вехи 4.5.
     *
     * До неё подвал был шире на «О компании»: страница есть в макете и в ТЗ,
     * но в закреплённое меню не входила — «трафик она не приносит, а пункт
     * меню стоит дорого». **Это объяснение отменено заказчиком** на
     * демонстрации 11.08.2026 (разбор — в докблоке `HEADER`), и оно
     * записано здесь прошедшим временем, а не удалено: без него следующий
     * читатель этой константы уберёт пункт из шапки обратно, найдя
     * убедительный довод там, где на самом деле стоит решение заказчика.
     *
     * Список остаётся отдельным от `HEADER` намеренно: совпадение составов
     * сейчас — это факт, а не правило, и первый же пункт, нужный только
     * подвалу (политика конфиденциальности, вакансии), разведёт их обратно.
     *
     * @var list<string>
     */
    private const array FOOTER = [
        'catalog.index',
        'services.index',
        'parts.index',
        'about.index',
        'contacts.index',
    ];

    /**
     * @return list<array{name: string, label: string, url: string}>
     */
    public static function header(): array
    {
        return self::links(self::HEADER);
    }

    /**
     * @return list<array{name: string, label: string, url: string}>
     */
    public static function footer(): array
    {
        return self::links(self::FOOTER);
    }

    /**
     * Пункты, у которых есть зарегистрированный роут.
     *
     * Пункт без роута выпадает, а не роняет страницу. Причина не в
     * снисходительности: шапка и подвал рендерятся на каждой странице сайта,
     * и переименованный роут положил бы весь сайт целиком, включая формы
     * заявок — единственное, ради чего сайт существует. Отсутствие пункта
     * ловится тестом до мержа (`LayoutTest` проверяет, что все ожидаемые
     * роуты зарегистрированы и попали в разметку), и это правильное место
     * для такой ошибки.
     *
     * Переходный период, ради которого механизм пригодился в первый раз,
     * кончился: «О компании» была объявлена в `LABELS` и `FOOTER` вехой 4.1,
     * а роут получила вехой 4.5 — и до тех пор пункт просто не выводился
     * вместо того, чтобы вести в 404. Сам отсев остаётся: он страхует
     * не переезд, а переименование роута.
     *
     * @param  list<string>  $names
     * @return list<array{name: string, label: string, url: string}>
     */
    private static function links(array $names): array
    {
        $links = [];

        foreach ($names as $name) {
            if (! Route::has($name)) {
                continue;
            }

            $links[] = [
                'name' => $name,
                'label' => self::LABELS[$name],
                'url' => route($name),
            ];
        }

        return $links;
    }
}
