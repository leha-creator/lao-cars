<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Ключи настроек сайта, значение которых — ссылка на медиабиблиотеку.
 *
 * Живёт в `app/Support/`, а не константой на странице настроек, по
 * правилу зависимостей из `ARCHITECTURE.md`: список нужен и форме
 * (`ManageSiteSettings`), и модели (`Media::usages()`), а модель не
 * должна знать о Filament-странице. Это чистые данные — ни диска, ни
 * HTTP, ни внешнего мира, — поэтому обращение к ним из модели слоёв
 * не нарушает. Тот же приём, что и в `ThumbnailPath`.
 *
 * Список — единственный источник правды: добавление второго медийного
 * ключа правится здесь, и оба потребителя видят его сразу. Совпадение
 * ключей с реальными полями формы проверяет тест.
 *
 * **Ключ настройки и путь внутрь её значения хранятся раздельно, и это
 * не многословность ради многословности.** Плоский список строк вида
 * `home.promo.image_id` заставляет потребителя угадывать границу между
 * ними по последней точке (`Str::beforeLast`) — для объекта догадка
 * верна, а для репитера нет: у `home.steps.*.image_id` она даёт ключ
 * `home.steps.*`, настройки с таким именем не существует, и проверка
 * использования не срабатывает НИКОГДА. Изображение, выбранное в этапе
 * покупки, считалось бы свободным и удалялось из библиотеки молча,
 * оставляя в jsonb висячий id, у которого нет внешнего ключа. Склеенная
 * строка выглядит аккуратнее — вернуть её значит вернуть этот отказ.
 */
final class MediaSettingKeys
{
    /**
     * Места, где значение настройки — ссылка на медиабиблиотеку.
     *
     * `setting` — ключ строки `site_settings`. `path` — путь внутрь её
     * jsonb-значения в нотации `data_get()`: `image_id` для объекта,
     * `*.image_id` для репитера, где таких значений столько же, сколько
     * элементов. `label` — как назвать это место человеку в перечне
     * использования перед удалением файла.
     *
     * @var list<array{setting: string, path: string, label: string}>
     */
    private const array KEYS = [
        [
            'setting' => 'home.promo',
            'path' => 'image_id',
            'label' => 'Настройки: промо-блок на главной',
        ],
        [
            'setting' => 'home.steps',
            'path' => '*.image_id',
            'label' => 'Настройки: этапы покупки на главной',
        ],
    ];

    /**
     * @return list<array{setting: string, path: string, label: string}>
     */
    public static function all(): array
    {
        return self::KEYS;
    }

    /**
     * Ключи настроек, встречающиеся в реестре, — без повторов.
     *
     * Одна настройка может содержать несколько медийных путей, и тест,
     * сверяющий реестр с формой, обязан спрашивать про ключ, а не про
     * путь: в реестре страницы настроек путей внутрь значения нет.
     *
     * @return list<string>
     */
    public static function settings(): array
    {
        return array_values(array_unique(array_column(self::KEYS, 'setting')));
    }
}
