<?php

declare(strict_types=1);

namespace App\Support;

use Illuminate\Support\Facades\Log;

/**
 * Адрес виджета Яндекс.Карт для страницы контактов (веха 4.5).
 *
 * **Почему виджет, а не карта на API-ключе.** Полное ТЗ просило «карту
 * с маршрутом (Яндекс.Карты/2ГИС API)», и в этой форме её отложили за
 * пределы MVP: ключ, SDK и серверная часть ради одного блока. Согласованный
 * с заказчиком упрощённый вариант ТЗ просит другое — «встроенную карту
 * (iframe Яндекс.Карт)». Основание отсрочки к ней не относится: у виджета
 * нет ни ключа, ни SDK, ни серверного кода — только адрес в `src`.
 *
 * **Почему список хостов, а не свободный URL.** Значение настройки едет
 * прямо в `src` iframe, то есть администратор панели описывает, чей сайт
 * покажется внутри нашей страницы. Свободный URL здесь — это `javascript:`
 * в атрибуте, кликджекинг поверх формы заявки и любая чужая страница под
 * нашим доменом в глазах посетителя. Список хостов — единственное место,
 * где это останавливается.
 *
 * **Проверок две, и это не дубль.** Правило валидации формы (`ManageSiteSettings`)
 * ловит опечатку в момент ввода и объясняет её человеку. Проверка здесь
 * ловит значение, приехавшее мимо формы, — сидом, миграцией, `psql`.
 * Форма без второй проверки — защита, которую обходит один `UPDATE`.
 *
 * `sandbox` на самом iframe при этом НЕ ставится, и это решение вехи:
 * виджету нужны скрипты и свой origin, то есть `allow-scripts allow-same-origin`,
 * а эта пара для чужого origin не ограничивает ничего — только создаёт
 * ощущение защиты. Настоящий контроль — список ниже.
 */
final class MapEmbed
{
    /**
     * Хосты, которым разрешено оказаться в `src` нашего iframe.
     *
     * Сравнение идёт по ПОЛНОМУ хосту, а не по вхождению подстроки:
     * `yandex.ru.evil.com` содержит «yandex.ru» и не имеет к нему
     * никакого отношения.
     *
     * @var list<string>
     */
    private const array ALLOWED_HOSTS = [
        'yandex.ru',
        'www.yandex.ru',
        'yandex.com',
        'www.yandex.com',
        'api-maps.yandex.ru',
    ];

    /**
     * Базовый адрес виджета, который геокодирует адрес текстом.
     */
    private const string WIDGET = 'https://yandex.ru/map-widget/v1/';

    /**
     * Масштаб карты для фолбэка: 16 — квартал вокруг точки.
     *
     * Вынесен константой, потому что это первое, что попросят подвинуть
     * на показе, и искать число внутри `http_build_query()` тогда придётся
     * по всему файлу.
     */
    private const int ZOOM = 16;

    /**
     * Адрес карты для страницы: настройка → виджет из адреса → ничего.
     *
     * Порядок именно такой. Заказчик получает работающую карту сразу, как
     * заполнил адрес компании, и настройку трогает, только если хочет свою —
     * с маркером из конструктора Яндекс.Карт. `null` означает «блока карты
     * на странице нет вовсе»: пустая рамка читается как поломка вёрстки,
     * а не как «карта не настроена».
     */
    public static function resolve(?string $configured, ?string $address): ?string
    {
        if ($configured !== null && $configured !== '') {
            if (self::isAllowed($configured)) {
                return $configured;
            }

            // URL целиком в лог не идёт: его содержимое пишет кто угодно
            // с доступом к форме настроек, а логи читают глазами и грепом.
            // Хоста достаточно, чтобы понять, что именно отклонили.
            Log::warning('[Карта] адрес виджета отклонён', [
                'setting' => 'contacts.map_embed',
                'host' => parse_url($configured, PHP_URL_HOST) ?: '—',
            ]);
        }

        if ($address === null || $address === '') {
            return null;
        }

        return self::WIDGET.'?'.http_build_query(['text' => $address, 'z' => self::ZOOM]);
    }

    /**
     * Годится ли адрес для `src` iframe.
     *
     * Публичный, потому что этим же методом проверяет ввод форма настроек:
     * одно правило в двух местах, а не два похожих.
     */
    public static function isAllowed(?string $url): bool
    {
        if ($url === null || $url === '') {
            return false;
        }

        $parts = parse_url($url);

        // `parse_url()` на мусоре возвращает `false`, а на строке без схемы —
        // массив без ключа `scheme`. Оба случая — не адрес.
        if (! is_array($parts)) {
            return false;
        }

        $scheme = isset($parts['scheme']) ? mb_strtolower((string) $parts['scheme']) : null;
        $host = isset($parts['host']) ? mb_strtolower((string) $parts['host']) : null;

        // Схема строго `https`. Не «не javascript»: список запрещённого
        // всегда неполон — завтра появится схема, о которой мы не думали.
        if ($scheme !== 'https' || $host === null) {
            return false;
        }

        return in_array($host, self::ALLOWED_HOSTS, strict: true);
    }

    /**
     * Ссылка «открыть в Яндекс.Картах» рядом с картой.
     *
     * Нужна не для красоты: iframe может не загрузиться — блокировщик,
     * корпоративная сеть, офлайн, — и без ссылки блок в этом случае
     * оказывается пустой рамкой на месте адреса.
     */
    public static function externalLink(?string $address): ?string
    {
        if ($address === null || $address === '') {
            return null;
        }

        return 'https://yandex.ru/maps/?'.http_build_query(['text' => $address, 'z' => self::ZOOM]);
    }
}
