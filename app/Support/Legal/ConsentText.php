/**
 * Согласие на обработку персональных данных: текст по умолчанию и редакция.
 *
 * **Почему это отдельный документ, а не раздел политики.** С 01.09.2025
 * согласие оформляется отдельно от иных документов, которые подтверждает
 * субъект (ч. 1 ст. 9 Федерального закона № 152-ФЗ). До этой правки чекбокс
 * формы заявки одной отметкой и давал согласие, и «принимал» политику,
 * а текста самого согласия на сайте не было вовсе. Теперь чекбокс ссылается
 * на страницу `/consent`, а политика упоминается под ним строкой без отметки.
 *
 * **Устройство повторяет `PrivacyPolicy` намеренно**, а не обобщено с ним:
 * документов два, третьего не предвидится, и общий базовый класс ради двух
 * наследников прятал бы различие, которое здесь главное, — у согласия нет
 * маркера незаполненных реквизитов, потому что реквизиты оператора в нём
 * подставлены с первой редакции.
 *
 * **Текст обязан совпадать с тем, что делает сайт.** Перечень данных
 * повторяет поля формы заявки и раздел 4 политики, цели — раздел 5, срок —
 * раздел 9 и `config('leads.retention_years')`. Правка формы, срока хранения
 * или состава передаваемого третьим лицам обязана дойти и сюда.
 *
 * Юридическую силу тексту даёт утверждение его оператором, а не этот файл:
 * на сайте действует то, что лежит в настройке и правится из панели. Здесь —
 * то, что ставится на чистую установку командой
 * `laocars:install-legal-settings`.
 *
 * Разметка — только теги, которые отдаёт `RichEditor` со вкладки
 * «Персональные данные»; правила её записи — в `LegalMarkup::canonical()`.
 */
