    /**
     * Ключ настройки с документом.
     *
     * Путь до значения знают страница `/consent`, форма настроек, команда
     * установки и приём заявки — константа, а не четыре копии строки.
     */
    public const string SETTING_KEY = 'legal.consent';

    /**
     * Значение настройки `legal.consent` целиком.
     *
     * Форма значения — та же, что у `legal.privacy`: один ключ с объектом
     * внутри, потому что реестр `ManageSiteSettings::KEYS` сверяется с сидом
     * по ключу целиком.
     *
     * @return array{body: string, version: string, effective_on: string}
     */
    public static function defaultSetting(): array
    {
        return [
            'body' => LegalMarkup::canonical(self::defaultBody()),
            'version' => '1.0',
            'effective_on' => '07.10.2026',
        ];
    }

    /**
     * Редакция текста согласия, действующая прямо сейчас, или `null`.
     *
     * Значение уходит в колонку `leads.consent_text_version` и отвечает на
     * вопрос «какой текст согласия видел этот клиент». Очищенное поле
     * возвращается как `null`, а не подменяется умолчанием: выдуманная
     * редакция в доказательстве согласия хуже отсутствующей — то же решение
     * и по той же причине, что у `PrivacyPolicy::currentVersion()`.
     */
    public static function currentVersion(): ?string
    {
        $version = data_get(Setting::get(self::SETTING_KEY), 'version');

        if (! is_string($version)) {
            return null;
        }

        $version = trim($version);

        return $version === '' ? null : $version;
    }

    /**
     * Текст документа по умолчанию.
     *
     * Nowdoc, а не heredoc — как в `PrivacyPolicy`: текст правит юрист,
     * и знак `$` или `{` в очередной редакции не должен превращаться
