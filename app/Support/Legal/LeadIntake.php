<?php

declare(strict_types=1);

namespace App\Support\Legal;

use App\Models\Setting;

/**
 * Приём заявок через сайт: включён он сейчас или нет (веха 4.17).
 *
 * **Зачем выключатель вообще нужен.** Уведомление об обработке персональных
 * данных подаётся в Роскомнадзор ДО начала обработки. Сайт же начинает
 * обработку в тот момент, когда принимает первую заявку, — значит между
 * выкладкой политики и подачей уведомления формы обязаны молчать. Включает
 * их человек, на вкладке «Персональные данные», после подачи.
 *
 * **Умолчание — «выключено», и это принципиально.** Нет строки настройки
 * (а на проде её не будет до `laocars:install-legal-settings`) — приёма нет.
 * Обратный выбор отказывал бы в безопасную сторону только пока строка
 * на месте, то есть ровно в тот единственный момент, ради которого
 * выключатель и сделан, вёл бы себя неправильно.
 *
 * Отдельным классом от `PrivacyPolicy`, хотя ключи соседние: документ
 * и приём заявок включаются по разным причинам и в разное время, и общий
 * класс склеил бы «что написано» с «что сейчас можно».
 */
final class LeadIntake
{
    public const string SETTING_KEY = 'legal.forms_enabled';

    /**
     * Принимает ли сайт заявки прямо сейчас.
     *
     * Сравнение строгое: значение приходит из jsonb, и `'0'`, `0` или `null`
     * из криво заполненной строки настройки не должны читаться как «можно».
     *
     * Читает закешированные настройки — той же выборкой, что шапка и подвал,
     * то есть без дополнительного запроса на каждый вызов.
     */
    public static function enabled(): bool
    {
        return Setting::get(self::SETTING_KEY, false) === true;
    }
}
