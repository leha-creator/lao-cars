     * Маркер незаполненного реквизита в тексте документа.
     *
     * ДВОЙНАЯ скобка, а не одинарная: одинарная встречается в живом тексте
     * (перечисления, ссылки на пункты закона), и сторож ловил бы её ложно
     * при каждом открытии страницы.
     */
    public const string PLACEHOLDER_MARK = '[[';

    /**
     * Значение настройки `legal.privacy` целиком.
     *
     * Форма значения — объект с тремя полями, прецедент `home.promo`.
     * Тремя отдельными ключами не делается: реестр `ManageSiteSettings::KEYS`
     * сверяется с сидом по ключу целиком, и три ключа дали бы три шанса
     * разойтись вместо одного.
     *
     * @return array{body: string, version: string, effective_on: string}
     */
    public static function defaultSetting(): array
    {
        return [
            'body' => self::canonical(self::defaultBody()),
            'version' => '1.0',
            'effective_on' => '26.08.2026',
        ];
    }

    /**
     * Текст в том виде, в каком его отдаёт редактор панели.
     *
     * **Зачем это вообще нужно.** `RichEditor` пропускает значение через
     * TipTap на СЕРВЕРЕ при заполнении формы: разметка пересобирается из
     * разобранного документа, и пробельные символы между блочными тегами
     * при этом исчезают. Значит текст, записанный в настройку «как написан
     * в исходнике», отличается от того, что форма вернёт из `getState()`, —
     * и `ManageSiteSettings::isChanged()` объявляет настройку изменённой
     * при ПЕРВОМ же сохранении, которого никто не делал. Дальше по цепочке
     * это даёт ложное срабатывание сторожа «текст изменён, версия не
     * поднята», то есть предупреждение, которое приучают игнорировать.
     *
     * Отсюда же `<li><p>…</p></li>` в самом тексте выше, а не привычное
     * `<li>…</li>`: узел списка в TipTap содержит блок, и редактор
     * дописывает абзац внутрь пункта сам. Написать «как красивее» значит
     * получить ту же ложную правку.
     *
     * **Про регулярное выражение.** Оно убирает пробельные символы только
     * МЕЖДУ двумя тегами (`>` … `<`). Пробел между словом и тегом
     * (`текст <strong>`) под него не подпадает и не теряется. Единственный
     * случай, который выражение испортило бы, — намеренный пробел между
     * двумя инлайновыми тегами (`</strong> <em>`), и в тексте выше такого
     * нет по построению.
     *
     * Сторож на всю конструкцию уже написан и стоит с вехи 3.5:
     * `it('reports nothing as changed when the form is saved untouched')`.
     * Разойдётся канонизация после обновления Filament — тест покраснеет,
     * а не промолчит.
     */
    private static function canonical(string $html): string
    {
        return (string) preg_replace('/>\s+</u', '><', trim($html));
    }

    /**
     * Редакция документа, действующая прямо сейчас, или `null`.
     *
     * Значение уходит в колонку `leads.consent_policy_version` — то есть
     * отвечает на вопрос «с каким текстом согласился этот клиент». Поэтому
     * очищенное поле возвращается как `null`, а не подменяется умолчанием
     * из `defaultSetting()`: выдуманная редакция в доказательстве согласия
     * хуже отсутствующей. Предупреждение о пустоте пишет вызывающая сторона
     * (`StoreLeadRequest`) — только там известен номер заявки, ради которого
     * запись в лог вообще имеет смысл.
     *
     * Читает закешированные настройки, то есть не добавляет запросов:
     * `Setting::get()` берёт значение из той же выборки, что шапка и подвал.
     */
    public static function currentVersion(): ?string
    {
        $version = data_get(Setting::get(self::SETTING_KEY), 'version');

        if (! is_string($version)) {
            return null;
        }

        $version = trim($version);

        return $version === '' ? null : $version;
    }

