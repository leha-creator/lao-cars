namespace App\Support\Legal;

use App\Models\Setting;

/**
 * Политика обработки персональных данных: текст по умолчанию, редакция
 * и маркер незаполненных реквизитов (веха 4.17).
 *
 * **Почему текст живёт здесь, а не строкой в сиде.** Прецедент прямой —
 * `'contacts.schedule' => WorkSchedule::defaultSetting()`. Документ занимает
 * несколько килобайт разметки, и вклеенный в `SiteSettingSeeder` между
 * телефоном и бегущей строкой он похоронил бы остальные сорок ключей: сид
 * перестал бы читаться как реестр. Вторая причина — тот же текст нужен
 * команде `laocars:install-legal-settings`, которая ставит настройки
 * на проде (сиды туда не выкатываются), и без общего источника копий
 * стало бы две.
 *
 * **Текст — черновик, а не готовый документ.** Разделы про состав данных,
 * цели и передачу написаны по фактическому коду: состав повторяет колонки
 * `leads`, передача называет Telegram и хостинг-провайдера, раздел о cookie
 * описывает единственную куку, которую сайт ставит на самом деле. Реквизиты
 * оператора заказчику ещё предстоит подставить — они оставлены видимыми
 * плейсхолдерами (см. `PLACEHOLDER_MARK`), и на них стоит сторож
 * в `PrivacyPageContent`. Юридическую силу тексту придаёт подпись оператора,
 * а не корректность этого файла, поэтому правится он из панели, а не отсюда.
 *
 * Разметка — только те теги, которые умеет отдать `RichEditor` со вкладки
 * «Персональные данные» (`h2`, `h3`, `p`, `ul`, `ol`, `li`, `strong`, `em`,
 * `a`). Любой другой тег первое же сохранение из панели молча выбросит,
 * и текст «поедет» без единой ошибки в логе.
 */
final class PrivacyPolicy
{
    /**
     * Ключ настройки с документом.
     *
     * Объявлен здесь, а не строкой по месту вызова: путь до значения знают
     * страница `/privacy`, форма настроек, команда установки и приём заявки,
     * и четыре копии строки разошлись бы на первом же переименовании.
     */
    public const string SETTING_KEY = 'legal.privacy';

