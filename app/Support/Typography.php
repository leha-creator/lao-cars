<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Русская типографика для абзацев сайта (веха 4.14, пункт 6 постановки).
 *
 * Заказчик показал пальцем: «в тексте „…сколько автомобилей подходит под
 * запрос, ещё до заявки“ перенесено на последнюю строку слово „заявки“,
 * надо либо чтобы было минимум два-три слова, либо чтобы всё уместилось
 * в двух строках».
 *
 * ПОЧЕМУ НЕ ХВАТАЕТ `text-pretty`. Это правильная база и она остаётся,
 * но она — РЕКОМЕНДАЦИЯ браузеру, а не гарантия: поддержка неполная,
 * а под `lg:text-right` в контейнере `max-w-110` результат непредсказуем.
 * Требование заказчика сформулировано числом, и число обязано
 * выполняться, а не выпрашиваться у движка вёрстки.
 *
 * НЕРАЗРЫВНЫЙ ПРОБЕЛ — СИМВОЛОМ U+00A0, А НЕ СУЩНОСТЬЮ `&nbsp;`.
 * Blade экранирует вывод `{{ }}`, и сущность напечаталась бы на странице
 * текстом «&nbsp;». Символ проходит как символ.
 *
 * Живёт в `app/Support/` по прецеденту `ThumbnailPath` и `WorkSchedule`:
 * чистая функция над строкой, без диска, БД и HTTP.
 */
final class Typography
{
    /** Неразрывный пробел, U+00A0. */
    public const string NBSP = "\u{00A0}";

    /**
     * Сколько слов максимум склеивать в хвосте.
     *
     * Заказчик просил «два-три», и три — верхняя граница, а не цель:
     * сколько получится в пределах длины ниже, столько и склеится.
     */
    private const int TAIL_WORDS = 3;

    /**
     * Предел длины склеенного хвоста в символах.
     *
     * ХВОСТ ОГРАНИЧЕН ДЛИНОЙ, А НЕ ТОЛЬКО ЧИСЛОМ СЛОВ. Склеить три слова
     * по девять букв в контейнере 440px значит вытолкнуть строку за край,
     * а переполнение хуже висячего слова: висячее слово некрасиво,
     * переполнение — сломано. Не влезает три — склеиваем два; не влезают
     * и они — оставляем как есть и полагаемся на `text-pretty`.
     */
    private const int TAIL_LIMIT = 20;

    /**
     * Однобуквенные и двухбуквенные предлоги, союзы и частицы.
     *
     * Подтягиваются к СЛЕДУЮЩЕМУ слову — правило русской типографики,
     * которое лечит ту же болезнь в середине абзаца: «в\u{00A0}Москве»,
     * «и\u{00A0}сервис». Список закрытый и короткий: тянуть за собой
     * словарь ради двух десятков служебных слов незачем.
     */
    private const string SHORT_WORDS = 'а|и|в|о|с|у|к|на|по|за|до|из|от|не|ни|но|то|же|бы|ли|да|во|со|ко|об|их|мы|вы|он|их';

    /**
     * Привязать хвост абзаца и подтянуть короткие слова.
     *
     * `null` и пустая строка проходят насквозь: вызывающему не должно
     * приходиться проверять их самому — иначе проверка появится
     * в семи местах и в одном из них будет забыта.
     */
    public static function tie(?string $text): ?string
    {
        if ($text === null || trim($text) === '') {
            return $text;
        }

        // Пробелы схлопываются в один, а переносы строк уходят.
        //
        // Не косметика: текст приходит сюда и из слота компонента, где он
        // разложен по строкам с отступом вёрстки, и склейка хвоста считала
        // бы длину вместе с переводами строк и пятнадцатью пробелами
        // отступа. В HTML такой пробел всё равно ничего не значит —
        // абзацы выводятся без `nl2br`, — а для расчёта значит, и врёт.
        //
        // ВНИМАНИЕ: с флагом `/u` класс `\s` в этой сборке PCRE ловит
        // и U+00A0 — проверено, `preg_match('/\s/u', "\u{00A0}")` даёт 1,
        // а без `/u` даёт 0. То есть нормализация снимает и неразрывные
        // пробелы тоже.
        //
        // Здесь это ровно то, что нужно: функция становится идемпотентной
        // — повторный вызов сначала разбирает прошлую склейку, потом
        // складывает её заново и приходит к тому же результату. Без такого
        // снятия двойной прогон (текст из настроек, случайно пропущенный
        // через `tie()` дважды) накапливал бы склейку и стягивал абзац
        // в одну неразрывную строку.
        $text = trim((string) preg_replace('/\s+/u', ' ', $text));

        return self::tieTail(self::tieShortWords($text));
    }

    /**
     * Подтянуть предлоги и союзы к следующему слову.
     *
     * Граница `(?<=^|\s)` вместо `\b`: `\b` сработал бы и внутри слова,
     * превратив «во-первых» в «во\u{00A0}-первых».
     */
    private static function tieShortWords(string $text): string
    {
        return (string) preg_replace(
            '/(?<=^|\s)('.self::SHORT_WORDS.')\s+/iu',
            '$1'.self::NBSP,
            $text,
        );
    }

    /**
     * Склеить последние слова абзаца, чтобы одно из них не осталось
     * на строке в одиночестве.
     */
    private static function tieTail(string $text): string
    {
        $text = rtrim($text);

        // Разбиение по ОБЫЧНОМУ пробелу: неразрывные, поставленные выше,
        // склеенными группами и должны остаться — «ещё до заявки» здесь
        // одно слово, а не три, и считать его за три значило бы склеить
        // втрое больше, чем просили.
        $words = preg_split('/ +/u', $text);

        if ($words === false || count($words) < 2) {
            return $text;
        }

        // Сколько слов войдёт в предел длины. Идём от большего к меньшему:
        // три, если помещаются, иначе два, иначе ничего.
        for ($take = min(self::TAIL_WORDS, count($words)); $take >= 2; $take--) {
            $tail = array_slice($words, -$take);

            if (mb_strlen(implode(' ', $tail)) <= self::TAIL_LIMIT) {
                return implode(' ', array_slice($words, 0, -$take))
                    .($take === count($words) ? '' : ' ')
                    .implode(self::NBSP, $tail);
            }
        }

        return $text;
    }
}
