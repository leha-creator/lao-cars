    public function run(): void
    {
        $settings = $this->settings();

        $existing = Setting::query()->whereIn('key', array_keys($settings))->count();

        foreach ($settings as $key => $value) {
            Setting::set($key, $value);
        }

        $created = count($settings) - $existing;

        $this->command?->info("[SiteSettingSeeder] настроек создано: {$created}, обновлено: {$existing}");
    }
