#!/usr/bin/env bash
#
# Единственное, что может сделать CI-ключ, войдя на сервер.
#
# Прописан принудительной командой в `authorized_keys` пользователя
# `laocars` рядом с публичной частью ключа деплоя:
#
#     command="/var/www/laocars/deploy/ci-deploy.sh",no-agent-forwarding,\
#     no-port-forwarding,no-pty,no-X11-forwarding ssh-ed25519 AAAA... laocars-ci
#
# ЗАЧЕМ. Решение 11 плана требует, чтобы скомпрометированный CI не давал
# интерактивного доступа. Обычный ключ в `authorized_keys` этого не даёт
# сам по себе: укравший приватную часть получает оболочку от `laocars`,
# то есть право писать в код приложения, читать `.env` со всеми
# секретами и запускать что угодно. Принудительная команда сводит его
# возможности к одной: выкатить ревизию из уже существующего origin.
#
# `no-pty` и запрет пробросов здесь не украшение: без них ключ годится
# как транспорт для туннеля внутрь сети, даже если shell недоступен.
#
# ЧЕГО ЭТО НЕ ДАЁТ. Выкатить можно ЛЮБУЮ ревизию, которая есть в origin,
# включая старую. Это осознанно — на том же механизме держится откат.

set -euo pipefail

REF="${SSH_ORIGINAL_COMMAND:-}"

# Пустая команда — штатный случай: workflow без `ref` выкатывает
# origin/master, и `deploy.sh` подставит его сам.
if [ -z "${REF}" ]; then
    exec /var/www/laocars/deploy/deploy.sh
fi

# Дальше — единственное место, где решается, что можно, а что нет.
#
# Разрешены только имена ревизий: SHA, теги, ветки и `origin/ветка`.
# Всё остальное отвергается ЦЕЛИКОМ, а не вычищается: попытка
# «отфильтровать опасные символы» из строки, которая пойдёт в shell,
# это гонка, в которой защищающийся всегда на шаг позади.
#
# Пробелов в разрешённом наборе нет намеренно: ими склеиваются
# несколько аргументов, а `deploy.sh` принимает ровно один.
if ! printf '%s' "${REF}" | grep -qE '^[A-Za-z0-9._/-]{1,200}$'; then
    echo "ci-deploy: недопустимая ревизия, выкат не выполнен." >&2
    exit 1
fi

# `..` отдельной проверкой: он проходит набор символов выше, но в git
# означает диапазон ревизий, а не ревизию.
case "${REF}" in
    *..*)
        echo "ci-deploy: диапазон ревизий недопустим, нужна одна ревизия." >&2
        exit 1
        ;;
esac

exec /var/www/laocars/deploy/deploy.sh "${REF}"
