#!/usr/bin/env bash
#
# Локальный монитор ЛАО КАРС. Cron каждые 5 минут от пользователя laocars:
#
#     */5 * * * * /var/www/laocars/deploy/healthcheck.sh >> /var/log/laocars/healthcheck.log 2>&1
#
# ЭТОТ СКРИПТ НЕ ЗАМЕНЯЕТ ВНЕШНИЙ МОНИТОР.
#
# Он следит за тем, что видно только изнутри: жив ли воркер, здоровы ли
# контейнеры, не забит ли диск, нет ли упавших задач. Упавший сервер
# о себе не сообщит — для этого заведён внешний монитор, стучащийся
# в https://laocars.ru/up снаружи.

set -uo pipefail

APP_DIR="/var/www/laocars"
STATE_FILE="/var/log/laocars/healthcheck.state"
DOMAIN="laocars.ru"
DISK_THRESHOLD=85

source "${APP_DIR}/deploy/notify.sh"

problems=()

# --- Сайт отвечает ---------------------------------------------------
#
# ЧЕРЕЗ --resolve ПО HTTPS, А НЕ `-H 'Host:' http://127.0.0.1/up`.
#
# После выпуска сертификата блок на порту 80 отдаёт 301, а `curl -f`
# на 3xx не падает: без `-L` проверка завершилась бы успехом, не дойдя
# до приложения. Монитор, который всегда отвечает «жив», хуже
# отсутствующего — на него рассчитывают. `--resolve` бьёт в петлю,
# но настоящим именем, поэтому заодно проверяется и сертификат.
if ! curl -fsS --max-time 15 --resolve "${DOMAIN}:443:127.0.0.1" "https://${DOMAIN}/up" > /dev/null 2>&1; then
    problems+=("сайт не отвечает на https://${DOMAIN}/up")
fi

# --- Воркер очереди --------------------------------------------------
#
# Без него заявки сохраняются, а уведомления копятся молча — самый
# дорогой класс отказа по роадмапу: снаружи всё работает, сотрудник
# не узнаёт о заявках.
if ! systemctl is-active --quiet laocars-queue; then
    problems+=("воркер laocars-queue не запущен")
fi

# --- Контейнеры баз --------------------------------------------------
for container in laocars-postgres laocars-redis; do
    status="$(docker inspect --format '{{.State.Health.Status}}' "${container}" 2>/dev/null || echo "нет контейнера")"

    if [ "${status}" != "healthy" ]; then
        problems+=("контейнер ${container}: ${status}")
    fi
done

# --- Диск ------------------------------------------------------------
#
# 40 ГБ делят медиа, бэкапы, volume баз, vendor и node_modules.
# Порог не формальность: исходники автомобилей весят по 3 МБ штука.
disk_used="$(df --output=pcent / | tail -n 1 | tr -dc '0-9')"

if [ -n "${disk_used}" ] && [ "${disk_used}" -gt "${DISK_THRESHOLD}" ]; then
    problems+=("диск заполнен на ${disk_used}%")
fi

# --- Упавшие задачи --------------------------------------------------
#
# Упавшее уведомление о заявке иначе не всплывёт нигде: заявка в базе
# есть, менеджер о ней не знает, ошибок на сайте нет.
#
# Считается запросом прямо в контейнер, а НЕ через `artisan tinker`,
# и на то две причины. Первая: скрипт запускается из cron от root
# (у `laocars` намеренно нет доступа к docker), а `artisan` от root
# создавал бы root-овые файлы в `storage/logs`, куда потом не сможет
# писать php-fpm — отказ тихий и проявляется не здесь. Вторая важнее:
# монитор обязан работать ТОГДА, КОГДА ПРИЛОЖЕНИЕ НЕ ПОДНИМАЕТСЯ,
# а `artisan` в этот момент падает вместе с ним и молчит о причине.
#
# `< /dev/null` обязателен: `exec -T` подключает stdin к контейнеру
# и без перенаправления psql съедает остаток вызывающего скрипта.
failed="$(docker compose -f "${APP_DIR}/compose.production.yml" exec -T postgres \
    psql -U laocars -d laocars -tAc 'select count(*) from failed_jobs;' < /dev/null 2>/dev/null | tr -dc '0-9')"

if [ -n "${failed}" ] && [ "${failed}" -gt 0 ]; then
    problems+=("в failed_jobs записей: ${failed}")
fi

# --- Досягаемость Telegram -------------------------------------------
#
# Проверяется ОТДЕЛЬНО от всего остального, потому что это единственная
# проверка, отказ которой ломает сам способ сообщить об отказе.
#
# С этого хостинга `api.telegram.org` доступен не по тому адресу,
# который отдаёт DNS: и локальный резолвер, и публичные возвращают
# 149.154.166.110, куда TCP не проходит. Рабочий адрес закреплён
# в `/etc/hosts`. Пин хрупкий — Telegram может перестать обслуживать
# этот адрес, — и тогда уведомления о заявках замолчат при полностью
# исправном снаружи сайте.
#
# Поэтому отказ пишется в ЛОГ ВСЕГДА, а не только уходит тревогой:
# тревога в этот момент как раз и не уйдёт.
tg_token="$(grep -E '^TELEGRAM_BOT_TOKEN=' "${APP_DIR}/.env" 2>/dev/null | cut -d= -f2-)"

if [ -n "${tg_token}" ]; then
    if ! curl -fsS --max-time 15 "https://api.telegram.org/bot${tg_token}/getMe" > /dev/null 2>&1; then
        printf '%s TELEGRAM НЕДОСТУПЕН: getMe не отвечает. Проверить пин в /etc/hosts (149.154.167.220 api.telegram.org). Уведомления о заявках НЕ УХОДЯТ.\n' "$(date '+%Y-%m-%d %H:%M:%S')"
        problems+=("Telegram недоступен — уведомления о заявках не уходят")
    fi
fi

# --- Решение об алерте -----------------------------------------------
#
# АЛЕРТ ПОСЛЕ ДВУХ НЕУДАЧ ПОДРЯД, А НЕ ПОСЛЕ ПЕРВОЙ.
#
# `php artisan down` во время выката отдаёт 503 ВСЕМ, включая `/up`,
# и однократная неудача в окне деплоя является нормой, а не аварией.
# Окно замерено задачей 13 плана и укладывается в один интервал cron.
previous_failures="$(cat "${STATE_FILE}" 2>/dev/null | tr -dc '0-9')"
previous_failures="${previous_failures:-0}"

if [ "${#problems[@]}" -gt 0 ]; then
    current_failures=$((previous_failures + 1))
    echo "${current_failures}" > "${STATE_FILE}"

    printf '%s ПРОБЛЕМЫ (подряд: %s):\n' "$(date '+%Y-%m-%d %H:%M:%S')" "${current_failures}"
    printf '  - %s\n' "${problems[@]}"

    # Ровно на второй неудаче, а не на каждой последующей: иначе авария
    # длиной в час даёт двенадцать одинаковых сообщений, и следующую
    # настоящую тревогу пролистают вместе с ними.
    if [ "${current_failures}" -eq 2 ]; then
        notify "$(printf 'Проблемы на проде:\n%s' "$(printf '  - %s\n' "${problems[@]}")")"
    fi

    exit 1
fi

# --- Восстановление --------------------------------------------------
#
# Отбой отправляется обязательно: без него непонятно, авария
# продолжается или прошла, и приходится идти смотреть руками.
if [ "${previous_failures}" -ge 2 ]; then
    notify "Восстановление: все проверки снова проходят."
fi

echo "0" > "${STATE_FILE}"

# В лог пишутся только смены состояния, а не каждая проверка: иначе
# файл превращается в шум, в котором авария неотличима от нормы.
if [ "${previous_failures}" -gt 0 ]; then
    printf '%s Все проверки пройдены (после %s неудач подряд).\n' "$(date '+%Y-%m-%d %H:%M:%S')" "${previous_failures}"
fi
