return [

    /*
     * Ключи VAPID — подпись, которой push-сервис браузера отличает наш
     * сервер от чужого. Генерируются один раз командой
     *
     *     php artisan webpush:vapid
     *
     * и после этого не меняются НИКОГДА: сменённая пара делает мёртвыми
     * все существующие подписки разом, а сотрудник об этом не узнает —
     * кнопка в кабинете по-прежнему показывает «этот браузер подписан».
     *
     * Незаполненные ключи — не ошибка, а штатное состояние локальной
     * машины и CI: канал `webpush` в этом случае пропускается с WARN
     * в лог `leads` и без исключения (см. `NewLeadNotification`).
     * Симметрично несконфигурированному Telegram вехи 3.7: заваливать
     * `failed_jobs` пятью попытками на каждый лид там, где push
     * заведомо некому доставить, незачем.
     *
     * Приватный ключ в браузер не попадает никогда. Публичный попадает
     * по назначению — он публичный.
     */
    'vapid' => [
        'subject' => env('VAPID_SUBJECT'),
        'public_key' => env('VAPID_PUBLIC_KEY'),
        'private_key' => env('VAPID_PRIVATE_KEY'),
        'pem_file' => env('VAPID_PEM_FILE'),
    ],

    /*
     * Модель подписки. Своя, а не пакетная: подписке нужны читаемое имя
     * устройства для списка в кабинете и скоуп выборки получателей.
     */
    'model' => App\Models\PushSubscription::class,

    'table_name' => env('WEBPUSH_DB_TABLE', 'push_subscriptions'),

    /*
     * Правка относительно апстрима: умолчание там — `mysql`, и на проде
     * с закешированным конфигом и незаданной `WEBPUSH_DB_CONNECTION`
     * пакет пошёл бы в несуществующее соединение. Берём то же соединение,
     * что и остальное приложение.
     */
    'database_connection' => env('WEBPUSH_DB_CONNECTION', env('DB_CONNECTION', 'pgsql')),

    'client_options' => [],

    /*
     * Дополнение полезной нагрузки до фиксированной длины: без него размер
     * сообщения выдаёт его содержимое наблюдателю трафика. Выключается
     * только ради старого Firefox на Android — у нас такой задачи нет.
     */
    'automatic_padding' => env('WEBPUSH_AUTOMATIC_PADDING', true),

];
